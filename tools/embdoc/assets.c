/* assets -- the stylesheet and the script every page of the site shares,
 * written by embdoc itself: no font, script or style comes from anywhere
 * else.
 *
 * The look is a datasheet's: one calm text column, rules rather than
 * boxes, tables ruled like a register map (a heavy rule above and below,
 * a light one under the head), code labelled by its language on the
 * block's edge, and a single accent, the green of a solder mask. The
 * theme follows the system's light or dark preference until the toggle
 * picks one, which is remembered. Under 1200 pixels the "On this page"
 * list folds above the text; under 860 the navigation becomes a drawer,
 * and wide tables and code scroll inside their own box, never the page.
 *
 * The script: the theme toggle, the drawer, the "On this page" list
 * following the reader, a copy button on code, and the search -- which
 * loads search-index.json on first use and ranks each section by where
 * the words are found: its heading, its page's title, its text. */
