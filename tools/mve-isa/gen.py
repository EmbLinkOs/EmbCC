#!/usr/bin/env python3
"""isa2.json, rank.json, synonyms.json -> src/arch/thumb/mve.inc

MVE's forms (ARMv8.1-M's vector extension) llvm-mc decodes, as tables:
each form's mnemonic, operand shape, opcode bits and fields (where each
bit goes and its weight), in llvm-mc's order of preference; and the type
spellings llvm-mc takes for each mnemonic. VPT's blocks (vpt, vpst) are
left out: the assembler's own code writes their masks."""
import json, os, re, sys

OUT = sys.argv[1] if len(sys.argv) > 1 else 'mve.inc'
T = json.load(open('isa2.json'))
RANK = {int(k): v for k, v in json.load(open('rank.json')).items()}
SYN = json.load(open('synonyms.json'))
SKIP = re.compile(r'^(vpt|vpst)')

E, seen = [], set()
for i, e in enumerate(T):
    if not e.get('base_ok') or SKIP.match(e['mnem']):
        continue
    key = (e['mnem'], e['shape'], e['base'], e['fieldmask'])
    if key in seen:
        continue
    seen.add(key)
    e['idx'] = i
    E.append(e)
ORDER = {i: n for n, i in enumerate(json.load(open('order.json')))} \
    if os.path.exists('order.json') else {}
E.sort(key=lambda e: (e['mnem'], e['shape'], ORDER.get(e['idx'], 1 << 30),
                      -RANK.get(e['idx'], 0)))

lines = ['/* MVE (Helium), generated by tools/mve-isa/gen.py from',
         ' * what llvm-mc decodes and assembles -- facts measured, not a table copied.',
         ' * Do not edit: regenerate. Included by neon.c alone, under mve_ names. */', '']
w = lines.append
fbits, oks, fields, insns = [], [], [], []
for e in E:
    f0 = len(fields)
    for f in e['fields']:
        b0 = len(fbits)
        for pos, wt in f['bits']:
            fbits.append((pos, abs(wt).bit_length() - 1, 1 if wt < 0 else 0))
        ok = f.get('ok', 'all')
        rule, o0, no = 0, len(oks), 0
        if isinstance(ok, list):
            rule, no = 2, len(ok)
            oks.extend(ok)
        fields.append((f['kind'], len(f['bits']), b0, f['v0'], rule, o0, no))
    insns.append((e['mnem'], e['shape'], e['base'] & 0xffffffff, f0, len(e['fields'])))
w('static const struct nn_fbit nn_fbits[] = {')
for i in range(0, len(fbits), 8):
    w('    ' + ' '.join('{%d,%d,%d},' % x for x in fbits[i:i + 8]))
w('};')
w('static const int nn_oks[] = {')
for i in range(0, len(oks), 16):
    w('    ' + ' '.join('%d,' % x for x in oks[i:i + 16]))
w('    0 };')
w('static const struct nn_field nn_fields[] = {')
for k, nb, b0, v0, rule, o0, no in fields:
    w("    {'%s', %d, %d, %d, %d, %d, %d}," % (k, nb, b0, v0, rule, o0, no))
w('};')
w('static const struct nn_insn nn_insns[] = {')
for mn, sh, base, f0, nf in insns:
    w('    {"%s", "%s", 0x%08xu, %d, %d},' % (mn, sh, base, f0, nf))
w('};')
w('static const struct nn_syn nn_syns[] = {')
have = {e['mnem'] for e in E}
for k, v in sorted(SYN.items()):
    if v in have:
        w('    {"%s", "%s"},' % (k, v))
w('};')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('%d forms, %d fields, %d field bits, %d synonyms -> %s' %
      (len(insns), len(fields), len(fbits), sum(1 for v in SYN.values() if v in have), OUT))
