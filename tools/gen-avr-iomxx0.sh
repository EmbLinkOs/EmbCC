#!/bin/sh
# gen-avr-iomxx0.sh [AVR-GCC]: writes include/avr/avr/iomxx0_1.h, the
# ATmega640/1280/2560 family's registers, bits and vectors, from
# avr-libc's descriptions of them (iomxx0_1.h and iom2560.h, the
# datasheet's names and addresses): avr-gcc's preprocessor gives each
# definition, in order, with the part's conditionals resolved. What
# EmbCC's own <avr/io.h>, <avr/sfr_defs.h> and <avr/common.h> define for
# every part (SREG, SP, _SFR_IO8, the memories, the signature), avr-libc's
# include guards, and the fuse and lock bits (EmbCC's 328P header has none)
# are left out. tests/golden/avr-io.sh compares the result with avr-libc's
# where avr-gcc is installed.
set -eu
AG=${1:-${AVR_GCC:-avr-gcc}}
here=$(dirname "$0")/..
out=$here/include/avr/avr/iomxx0_1.h
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
echo '#include <avr/io.h>' | "$AG" -mmcu=atmega2560 -dD -E - > "$tmp/dd.txt"
python3 - "$tmp/dd.txt" "$out" <<'PY'
import re, sys
dd, out = sys.argv[1:]
keep_files = ("iomxx0_1.h", "iom2560.h", "portpins.h")
generic = {"SREG", "SPL", "SPH", "SP", "RAMSTART", "RAMEND", "XRAMEND", "XRAMSIZE", "E2END",
           "E2PAGESIZE", "FLASHEND", "SPM_PAGESIZE", "SIGNATURE_0", "SIGNATURE_1", "SIGNATURE_2",
           "AVR_STACK_POINTER_HI_ADDR", "AVR_STACK_POINTER_HI_REG", "AVR_STACK_POINTER_LO_ADDR",
           "AVR_STACK_POINTER_LO_REG", "AVR_STACK_POINTER_REG", "AVR_STATUS_ADDR", "AVR_STATUS_REG"}
lines, cur = [], ""
for l in open(dd):
    m = re.match(r'# \d+ "([^"]*)"', l)
    if m:
        cur = m.group(1)
        continue
    m = re.match(r"#define (\w+)(\([^)]*\))?\s*(.*)", l)
    if not m or not cur.endswith(keep_files):
        continue
    name, args, val = m.group(1), m.group(2) or "", m.group(3).strip()
    if (name in generic or name.startswith("_AVR_") or name.startswith("__") or
            re.match(r"(FUSE_|LOCK|BLB|LB_|[LHE]FUSE|FUSEMEMSIZE|SLEEP_MODE|__LOCK|__BOOT)", name) or
            name.startswith("SP") and re.match(r"SP\d+$", name) or name.startswith("SREG_")):
        continue
    if not val:
        continue
    lines.append(f"#define {name}{args} {val}")
with open(out, "w") as f:
    f.write("""/* EmbCC's register file for the ATmega640/1280/2560 family, of which EmbCC
 * takes the ATmega1280 and the ATmega2560 (-mmcu=): the Arduino Mega's.
 * Included by <avr/io.h>; not meant to be included directly.
 *
 * Generated by tools/gen-avr-iomxx0.sh from avr-libc's descriptions of the
 * family (iomxx0_1.h, iom2560.h, portpins.h): every register, bit and
 * vector, under the datasheet's names, in avr-libc's order. Registers
 * 0x00-0x3f are named by their I/O address (_SFR_IO8), the extended I/O
 * registers by their data address (_SFR_MEM8, _SFR_MEM16). The two parts
 * differ in their memories and signature only, which <avr/io.h> sets.
 * tests/golden/avr-io.sh compares every one with avr-libc's where avr-gcc
 * is installed, and QEMU's mega and mega2560 machines run programs on
 * them. */
#ifndef _AVR_IOMXX0_1_H_
#define _AVR_IOMXX0_1_H_

""")
    f.write("\n".join(lines) + "\n")
    # what avr-libc's <avr/common.h> adds for a part with RAMPZ and EIND
    f.write("""
/* RAMPZ and EIND, as <avr/common.h> names them on a part that has them */
#define AVR_RAMPZ_REG RAMPZ
#define AVR_RAMPZ_ADDR _SFR_MEM_ADDR(RAMPZ)
#define AVR_EXTENDED_INDIRECT_REG EIND
#define AVR_EXTENDED_INDIRECT_ADDR _SFR_MEM_ADDR(EIND)
""")
    f.write("\n#endif /* _AVR_IOMXX0_1_H_ */\n")
print(f"{len(lines)} definitions")
PY
