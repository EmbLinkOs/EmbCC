#!/usr/bin/env python3
# gen-many-params-test.py -- writes tests/exec/many-params.c: C17's
# translation limit (5.2.4.1), 127 parameters in one definition and 127
# arguments in one call, of one type and of eight mixed ones, through a
# prototype, a pointer and `...`. The expected checksums are computed here,
# in the same uint32_t arithmetic the program does.
#
#     python3 tools/gen-many-params-test.py > tests/exec/many-params.c

N = 127
M = 0xffffffff

TYPES = ['signed char', 'short', 'int', 'long long', 'float', 'double',
         'struct cs', 'unsigned']


def val(t, i):
    """(the argument as C source, its contribution to the checksum)"""
    if t == 'signed char':
        v = i % 100 - 50
        return '%d' % v, v
    if t == 'short':
        v = i * 100 - 3000
        return '%d' % v, v
    if t == 'int':
        v = i * 211 - 13000
        return '%d' % v, v
    if t == 'long long':
        v = i * 1000000007 - 3
        return '%dLL' % v, (v ^ (v >> 32))
    if t == 'float':
        return "%d.5f" % i, 4 * i + 2         # (int32_t)(x * 4)
    if t == 'double':
        return '%d.25' % i, 4 * i + 1
    if t == 'struct cs':
        return '(struct cs){ %d, %d }' % (i, -i), i + 3 * -i
    if t == 'unsigned':
        return '%du' % (i * 7), i * 7
    raise ValueError(t)


def term(t, name):
    if t == 'long long':
        return '(uint32_t)(%s ^ (%s >> 32))' % (name, name)
    if t in ('float', 'double'):
        return '(uint32_t)(int32_t)(%s * 4)' % name
    if t == 'struct cs':
        return '(uint32_t)(%s.c + 3 * %s.s)' % (name, name)
    return '(uint32_t)%s' % name


def check(vals):
    s = 0
    for v in vals:
        s = (s * 3 + (v & M)) & M
    return s


out = []
out.append('/* GENERATED by tools/gen-many-params-test.py -- edit that, not this.')
out.append(' *')
out.append(' * C17 5.2.4.1: an implementation translates a function definition with')
out.append(' * 127 parameters and a call with 127 arguments. EmbCC stopped at 32 --')
out.append(' * the parameter types were an array of 32 inside every type, the')
out.append(' * arguments one of 32 inside every expression. */')
out.append('// expect-exit: 42')
out.append('#include <stdarg.h>')
out.append('#include <stdint.h>')
out.append('')
out.append('struct cs { signed char c; short s; };')
out.append('')

# one type: int, weighted so that a swapped pair of arguments shows
plist = ', '.join('int a%d' % i for i in range(N))
out.append('__attribute__((noinline)) static uint32_t ints(%s)' % plist)
out.append('{')
out.append('    uint32_t s = 0;')
for i in range(N):
    out.append('    s = s * 3u + (uint32_t)a%d;' % i)
out.append('    return s;')
out.append('}')
out.append('')
int_vals = [i * 5 - 300 for i in range(N)]
int_args = ', '.join('%d' % v for v in int_vals)

# mixed
mtypes = [TYPES[i % len(TYPES)] for i in range(N)]
plist = ', '.join('%s m%d' % (t, i) for i, t in enumerate(mtypes))
out.append('__attribute__((noinline)) static uint32_t mixed(%s)' % plist)
out.append('{')
out.append('    uint32_t s = 0;')
for i, t in enumerate(mtypes):
    out.append('    s = s * 3u + %s;' % term(t, 'm%d' % i))
out.append('    return s;')
out.append('}')
out.append('')
margs, mvals = [], []
for i, t in enumerate(mtypes):
    a, v = val(t, i)
    margs.append(a)
    mvals.append(v)

# variadic: the count, then 126 ints -- 127 arguments
out.append('__attribute__((noinline)) static uint32_t va(int n, ...)')
out.append('{')
out.append('    va_list ap;')
out.append('    uint32_t s = 0;')
out.append('    va_start(ap, n);')
out.append('    for (int k = 0; k < n; k++)')
out.append('        s = s * 3u + (uint32_t)va_arg(ap, int);')
out.append('    va_end(ap);')
out.append('    return s;')
out.append('}')
out.append('')
va_vals = [300 - i * 4 for i in range(N - 1)]

out.append('int main(void)')
out.append('{')
out.append('    uint32_t (*fp)(%s) = ints;' % ', '.join(['int'] * N))
out.append('    int ok = 0;')
out.append('    ok += ints(%s) == %du;' % (int_args, check(int_vals)))
out.append('    ok += fp(%s) == %du;' % (int_args, check(int_vals)))
out.append('    ok += mixed(%s) == %du;' % (', '.join(margs), check(mvals)))
out.append('    ok += va(%d, %s) == %du;' % (N - 1, ', '.join('%d' % v for v in va_vals),
                                          check(va_vals)))
out.append('    return ok == 4 ? 42 : ok;')
out.append('}')
print('\n'.join(out))
