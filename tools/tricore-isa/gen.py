#!/usr/bin/env python3
"""isa3.json, relocs.json, narrow.json, rank.json -> src/arch/tricore/isa.inc

The TriCore instruction set as tables: every form (a mnemonic, the shape of
its operands, its length, its opcode bits), every operand field (where each
of its bits goes, what value it has with them clear, which values GNU as
takes), the relocation a symbol in a field gets, and which 3-operand forms
narrow to 2 when the destination is a source."""
import json, os, sys, re

OUT = sys.argv[1] if len(sys.argv) > 1 else 'isa.inc'
T = json.load(open('isa3.json'))
R = json.load(open('relocs.json'))
N = json.load(open('narrow.json'))
RANK = {int(k): v for k, v in json.load(open('rank.json')).items()}
RN = json.load(open('relnums.json'))
GR = json.load(open('gnures.json')) if os.path.exists('gnures.json') else {'set': {}, 'mirror': {}}
OPS = ['sym', 'hi:sym', 'lo:sym', 'sm:sym', 'up:sym', 'oth']

# drop what GNU never takes, and duplicates of one encoding under one shape
seen = set()
E = []
for i, e in enumerate(T):
    if not e.get('gnu_base_ok'):
        # a form whose small shift GNU takes only as 1
        fix = False
        for f in e['fields']:
            if f['kind'] == 'N' and len(f['bits']) <= 2 and not f.get('ok'):
                f['ok'] = [f['v0'] + min(b[1] for b in f['bits'])] if f['bits'] else [f['v0']]
                fix = True
        if not fix:
            continue
    key = (e['mnem'], e['shape'], e['len'], e['base'], e['fieldmask'])
    if key in seen:
        continue
    seen.add(key)
    e['idx'] = i
    E.append(e)

# an entry another of its mnemonic, shape and length covers -- the same
# opcode, with operand bits where this one has fixed ones (a decode of a
# reserved pattern) -- is that one's special case: dropped
def covers(a, b):
    return (a is not b and a['fieldmask'] & b['fieldmask'] == b['fieldmask'] and
            a['fieldmask'] != b['fieldmask'] and
            (b['base'] & ~a['fieldmask']) == (a['base'] & ~a['fieldmask']))
grp = {}
for e in E:
    grp.setdefault((e['mnem'], e['shape'], e['len']), []).append(e)
E = [e for e in E if not any(covers(a, e) for a in grp[(e['mnem'], e['shape'], e['len'])])]
for e in E:
    for f in e['fields']:
        if isinstance(f['v0'], int) and not -(1 << 31) <= f['v0'] < (1 << 31):
            sys.exit('%s %s: a field zero of %#x' % (e['mnem'], e['shape'], f['v0']))
E.sort(key=lambda e: (e['mnem'], e['shape'], e['len'], -RANK.get(e['idx'], 0)))
pos = {e['idx']: n for n, e in enumerate(E)}

lines = []
w = lines.append
w('/* The TriCore instruction set (TC1.6.2), generated by tools/tricore-isa/gen.py')
w(' * from what GNU objdump decodes and GNU as accepts -- facts measured, not a')
w(' * table copied. Do not edit: regenerate. */')

w('')
fbits, oks, fields = [], [], []
insns = []
for e in E:
    f0 = len(fields)
    for f in e['fields']:
        b0 = len(fbits)
        for bb in f['bits']:
            wt = bb[1]
            sh = abs(wt).bit_length() - 1
            fbits.append((bb[0], sh, 1 if wt < 0 else 0))
        ok = f.get('ok', 'all')
        rule, o0, no = 0, len(oks), 0
        if ok == 'even':
            rule = 1
        elif isinstance(ok, list):
            rule = 2
            oks.extend(ok)
            no = len(ok)
        v0 = f['v0'] if not isinstance(f['v0'], str) else 0
        kind = f['kind']
        if f['target']:
            kind = 'L'
        fields.append((kind, len(f['bits']), b0, v0, rule, o0, no))
    # what GNU writes in reserved bits: a constant, or a field's value again
    # (kind M: field v0's value at bit fb)
    base = e['base'] | GR['set'].get(str(e['idx']), 0)
    nf = len(e['fields'])
    mir = GR['mirror'].get(str(e['idx']))
    if mir:
        fields.append(('M', 0, mir[1], mir[0], 0, 0, 0))
        nf += 1
    insns.append((e['mnem'], e['shape'], e['len'], base & 0xffffffff, f0, nf))

w('static const struct tc_fbit tc_fbits[] = {')
for i in range(0, len(fbits), 8):
    w('    ' + ' '.join('{%d,%d,%d},' % x for x in fbits[i:i + 8]))
w('};')
w('static const int tc_oks[] = {')
for i in range(0, len(oks), 16):
    w('    ' + ' '.join('%d,' % x for x in oks[i:i + 16]))
w('    0 };')
w('static const struct tc_field tc_fields[] = {')
for k, nb, b0, v0, rule, o0, no in fields:
    w("    {'%s', %d, %d, %d, %d, %d, %d}," % (k, nb, b0, v0, rule, o0, no))
w('};')
w('static const struct tc_insn tc_insns[] = {')
for mn, sh, ln, base, f0, nf in insns:
    w('    {"%s", "%s", %d, 0x%08xu, %d, %d},' % (mn, sh, ln, base, f0, nf))
w('};')

# symbol rules: for (mnemonic, shape, field, operator), the form GNU took and
# the relocations; a statement longer than its form is the long branch
def match_entry(o):
    ln = o['len']
    cands = [e for e in E if e['mnem'] == o['mnem'] and e['shape'] == o['shape'] and e['len'] == ln]
    for e in cands:
        if (o['word'] & ~e['fieldmask'] & ~e['reserved']) == (e['base'] & ~e['reserved']):
            return e
    return None

ATOM = re.compile(r'%sp|%[dae](?:1[0-5]|[0-9])|[A-Za-z_.][A-Za-z0-9_.]*|-?0x[0-9a-f]+|-?[0-9]+')
def stmt_atoms(text, field):
    ops = text.split(' ', 1)[1] if ' ' in text else ''
    out = []
    for m in re.finditer(r'%sp|%[dae](?:1[0-5]|[0-9])[lu]{0,2}|\$[a-z0-9_]+|(?:hi:|lo:|sm:|up:)?[A-Za-z_.][A-Za-z0-9_.]*|-?0x[0-9a-f]+|-?[0-9]+', ops):
        a = m.group(0)
        if a == '%sp':
            out.append(('A', 10))
        elif re.match(r'%[dae]\d', a):
            out.append((a[1].upper(), int(re.match(r'%[dae](\d+)', a).group(1))))
        elif re.match(r'-?(0x)?[0-9]', a):
            out.append(('N', int(a, 0)))
        elif a in ('c', 'r', 'i'):
            continue
        else:
            out.append(('SYM', 0))
    return out

def match_other(o):
    sa = stmt_atoms(o['text'], o['field'])
    for e in E:
        if e['len'] != o['len'] or e['mnem'] == o['mnem'] and e['shape'] == o['shape']:
            continue
        if (o['word'] & ~e['fieldmask'] & ~e['reserved']) != (e['base'] & ~e['reserved']):
            continue
        mp = []
        for f in e['fields']:
            v = f['v0'] + sum(b[1] for b in f['bits'] if (o['word'] >> b[0]) & 1 and b[1])
            k = None
            if f['kind'] in 'DAE':
                k = next((i for i, a in enumerate(sa) if a == (f['kind'], v)), None)
            elif f['kind'] == 'N':
                k = next((i for i, a in enumerate(sa) if a[0] == 'SYM'), None)
                if k is not None and any(m == k for m in mp):
                    k = next((i for i, a in enumerate(sa) if a == ('N', v)), None)
            if k is None:
                break
            mp.append(k)
        else:
            if len(mp) == len(e['fields']):
                return e, ''.join(str(k) for k in mp)
    return None, ''

rules = []
for o in R:
    if 'refused' in o:
        rules.append((o['mnem'], o['shape'], o['field'], OPS.index(o['op']), -2, 0, 0, 0, ''))
        continue
    rs = [(off, RN.get(t, 0)) for off, t, s in o['relocs'] if t != 'R_TRICORE_RELAX']
    relax = any(t == 'R_TRICORE_RELAX' for off, t, s in o['relocs'])
    if o['len'] in (2, 4):
        e = match_entry(o)
        mp = ''
        if e is None and rs:
            # GNU wrote another form -- `add d0, sym` as `add d0, d0, sym`,
            # `cmov` as `sel`: the entry whose bits it is, and which of the
            # statement's operands each of its fields takes
            e, mp = match_other(o)
        if e is None or not rs:
            continue
        rules.append((o['mnem'], o['shape'], o['field'], OPS.index(o['op']), pos[e['idx']],
                      rs[0][1], rs[0][0], 1 if relax else 0, mp))
    else:
        # the long form: an inverted branch over `j SYM`
        rules.append((o['mnem'], o['shape'], o['field'], OPS.index(o['op']), -1,
                      rs[0][1] if rs else 0, rs[0][0] if rs else 0, o['len'], ''))
w('static const struct tc_symrule tc_symrules[] = {')
seen_r = set()
for r in rules:
    if r in seen_r:
        continue
    seen_r.add(r)
    w('    {"%s", "%s", %d, %d, %d, %d, %d, %d, "%s"},' % r)
w('};')
w('static const struct tc_narrow tc_narrows[] = {')
for k, v in sorted(N.items()):
    mn, sh = k.split(' ')
    a = 1 if v.get('a') == 2 else 0
    b = 1 if v.get('b') == 2 else 0
    if a or b:
        w('    {"%s", "%s", %d, %d},' % (mn, sh, a, b))
w('};')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('%d forms, %d fields, %d field bits, %d symbol rules -> %s' %
      (len(insns), len(fields), len(fbits), len(rules), OUT))
