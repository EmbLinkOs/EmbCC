#!/usr/bin/env python3
# gen-libm-float-table.py -- the reference table of tests/exec/libm-float.c:
# each float function's result for chosen float inputs, from Python's
# double math rounded once to float, as bit patterns. Writes the enum to
# stderr and the table to stdout; paste both into the test.
import math, struct
def f(x):  # round to float
    try:
        return struct.unpack('<f', struct.pack('<f', x))[0]
    except OverflowError:
        return math.inf if x > 0 else -math.inf
def bits(x): return struct.unpack('<I', struct.pack('<f', f(x)))[0]
def fl(v): return f(v)
xs_trig = [0.0, 1e-6, 0.1, 0.5, 0.7853982, 1.0, 1.5707964, 2.0, 3.1415927, 4.0, 10.0, 100.0, 1000.5, -0.3, -2.5, 12345.678]
xs_inv  = [0.0, 1e-5, 0.1, 0.5, 0.9, 0.99, 1.0, -0.25, -0.75, -1.0]
xs_pos  = [1e-30, 1e-5, 0.1, 0.5, 1.0, 1.5, 2.0, 10.0, 123.456, 1e10, 3.4e37]
xs_any  = [-20.0, -3.5, -1.0, -0.1, 0.0, 1e-7, 0.1, 0.5, 1.0, 2.5, 10.0, 20.0, 80.0]
xs_rnd  = [-2.5, -1.5, -0.5, -0.49999997, -0.0, 0.0, 0.49999997, 0.5, 1.5, 2.5, 3.7, -3.7, 8388607.5, 1e9]
rows = []
def add(name, fn, xs, nargs=1, ys=None):
    for x in xs:
        if nargs == 1:
            xv = fl(x)
            try: r = float(fn(xv))
            except (ValueError, OverflowError): continue
            if r == 0 and name in ('floor', 'ceil', 'trunc', 'round', 'sin', 'tan', 'atan', 'tanh', 'sinh', 'expm1', 'asin', 'cbrt'):
                r = math.copysign(0.0, xv)   # C keeps the zero's sign; Python's int results lose it
            rows.append((name, bits(xv), 0, bits(r)))
        else:
            for y in ys:
                xv, yv = fl(x), fl(y)
                try: r = fn(xv, yv)
                except (ValueError, OverflowError, ZeroDivisionError): continue
                if r != r: continue
                rows.append((name, bits(xv), bits(yv), bits(r)))
add('sin', math.sin, xs_trig); add('cos', math.cos, xs_trig); add('tan', math.tan, [x for x in xs_trig if abs(abs(x) - 1.5707964) > 1e-3])
add('asin', math.asin, xs_inv); add('acos', math.acos, xs_inv); add('atan', math.atan, xs_any)
add('sinh', math.sinh, [x for x in xs_any if abs(x) < 80]); add('cosh', math.cosh, [x for x in xs_any if abs(x) < 80]); add('tanh', math.tanh, xs_any)
add('exp', math.exp, [x for x in xs_any if x < 80]); add('expm1', math.expm1, [x for x in xs_any if x < 80])
add('log', math.log, xs_pos); add('log10', math.log10, xs_pos); add('log2', math.log2, xs_pos)
add('exp2', lambda x: 2.0 ** x, [x for x in xs_any if x < 80])
add('sqrt', math.sqrt, xs_pos + [0.0, 2.0, 3.0]); add('cbrt', lambda x: math.copysign(abs(x) ** (1/3), x) if x else x, [-27.0, -8.0, -1.0, 0.0, 1e-6, 1.0, 2.0, 8.0, 27.0, 1000.0])
add('floor', math.floor, xs_rnd); add('ceil', math.ceil, xs_rnd); add('trunc', math.trunc, xs_rnd)
add('round', lambda x: math.copysign(math.floor(abs(x) + 0.5), x) if abs(x) - math.floor(abs(x)) != 0.5 or True else 0, [x for x in xs_rnd if x not in (-0.49999997, 0.49999997)])
rows.append(('round', bits(0.49999997), 0, bits(0.0))); rows.append(('round', bits(-0.49999997), 0, bits(-0.0)))
add('pow', math.pow, [0.5, 1.5, 2.0, 10.0, 0.9], 2, [-3.0, -0.5, 0.0, 0.5, 2.0, 7.25])
add('atan2', math.atan2, [-1.0, 0.0, 1.0, 3.0], 2, [-2.0, 0.5, 1.0, 4.0])
add('hypot', math.hypot, [0.0, 3.0, 1e-20, 1e20], 2, [4.0, 1e-20, 5.0])
add('fmod', math.fmod, [5.5, -5.5, 100.0, 1e10], 2, [2.0, -3.0, 0.7])
names = sorted(set(r[0] for r in rows))
print('/* generated by gen.py: %d cases */' % len(rows))
print('static const struct ref refs[] = {')
for n, a, b, r in rows:
    print('    { F_%s, 0x%08xu, 0x%08xu, 0x%08xu },' % (n.upper(), a, b, r))
print('};')
print('enum {', ', '.join('F_%s' % n.upper() for n in names), '};', file=open('/dev/stderr', 'w'))
