#!/usr/bin/env python3
"""Write include/pic32/cp0defs.h: the MIPS32 coprocessor 0 registers by
name, as XC32's header of that name gives them to PIC32 code.

    python3 tools/gen-cp0defs.py > include/pic32/cp0defs.h

One row per register (number and select) and one per field (position and
length), from the MIPS32 and microAptiv architecture manuals; the C and
assembly forms are both made from the same row, so they cannot disagree.
"""

REGS = [
    ("INDEX", 0, 0), ("RANDOM", 1, 0), ("ENTRYLO0", 2, 0), ("ENTRYLO1", 3, 0),
    ("CONTEXT", 4, 0), ("USERLOCAL", 4, 2), ("PAGEMASK", 5, 0),
    ("PAGEGRAIN", 5, 1), ("WIRED", 6, 0), ("HWRENA", 7, 0),
    ("BADVADDR", 8, 0), ("BADINSTR", 8, 1), ("BADINSTRP", 8, 2),
    ("COUNT", 9, 0), ("ENTRYHI", 10, 0), ("COMPARE", 11, 0),
    ("STATUS", 12, 0), ("INTCTL", 12, 1), ("SRSCTL", 12, 2),
    ("SRSMAP", 12, 3), ("VIEW_IPL", 12, 4), ("SRSMAP2", 12, 5),
    ("CAUSE", 13, 0), ("VIEW_RIPL", 13, 4), ("NESTEDEXC", 13, 5),
    ("EPC", 14, 0), ("NESTEDEPC", 14, 2), ("PRID", 15, 0), ("EBASE", 15, 1),
    ("CDMMBASE", 15, 2), ("CONFIG", 16, 0), ("CONFIG1", 16, 1),
    ("CONFIG2", 16, 2), ("CONFIG3", 16, 3), ("CONFIG4", 16, 4),
    ("CONFIG5", 16, 5), ("CONFIG7", 16, 7), ("LLADDR", 17, 0),
    ("WATCHLO", 18, 0), ("WATCHHI", 19, 0), ("DEBUG", 23, 0),
    ("TRACECONTROL", 23, 1), ("TRACECONTROL2", 23, 2),
    ("USERTRACEDATA1", 23, 3), ("TRACEBPC", 23, 4), ("DEBUG2", 23, 6),
    ("DEPC", 24, 0), ("USERTRACEDATA2", 24, 3), ("PERFCTL0", 25, 0),
    ("PERFCNT0", 25, 1), ("PERFCTL1", 25, 2), ("PERFCNT1", 25, 3),
    ("ERRCTL", 26, 0), ("CACHEERR", 27, 0), ("TAGLO", 28, 0),
    ("DATALO", 28, 1), ("ERROREPC", 30, 0), ("DESAVE", 31, 0),
    ("KSCRATCH1", 31, 2), ("KSCRATCH2", 31, 3),
]

# (register, field, position, length)
FIELDS = [
    ("STATUS", "IE", 0, 1), ("STATUS", "EXL", 1, 1), ("STATUS", "ERL", 2, 1),
    ("STATUS", "UM", 4, 1), ("STATUS", "IM0", 8, 1), ("STATUS", "IM1", 9, 1),
    ("STATUS", "IPL", 10, 6), ("STATUS", "CEE", 17, 1),
    ("STATUS", "NMI", 19, 1), ("STATUS", "SR", 20, 1), ("STATUS", "TS", 21, 1),
    ("STATUS", "BEV", 22, 1), ("STATUS", "MX", 24, 1), ("STATUS", "RE", 25, 1),
    ("STATUS", "FR", 26, 1), ("STATUS", "RP", 27, 1), ("STATUS", "CU0", 28, 1),
    ("STATUS", "CU1", 29, 1),
    ("CAUSE", "EXCCODE", 2, 5), ("CAUSE", "IP0", 8, 1), ("CAUSE", "IP1", 9, 1),
    ("CAUSE", "RIPL", 10, 6), ("CAUSE", "IV", 23, 1), ("CAUSE", "DC", 27, 1),
    ("CAUSE", "CE", 28, 2), ("CAUSE", "TI", 30, 1), ("CAUSE", "BD", 31, 1),
    ("INTCTL", "VS", 5, 5), ("INTCTL", "IPPCI", 26, 3),
    ("INTCTL", "IPTI", 29, 3),
    ("SRSCTL", "CSS", 0, 4), ("SRSCTL", "PSS", 6, 4), ("SRSCTL", "ESS", 12, 4),
    ("SRSCTL", "EICSS", 18, 4), ("SRSCTL", "HSS", 26, 4),
    ("CONFIG", "K0", 0, 3), ("CONFIG", "MT", 7, 3), ("CONFIG", "AR", 10, 3),
    ("CONFIG", "AT", 13, 2), ("CONFIG", "BE", 15, 1),
    ("EBASE", "CPUNUM", 0, 10), ("EBASE", "EBASE", 12, 18),
]

HEAD = """\
/* <cp0defs.h> -- the MIPS32 coprocessor 0 registers by name, as XC32's
 * header of this name gives them to PIC32 code. EmbCC's own: generated by
 * tools/gen-cp0defs.py from the MIPS32 and microAptiv architecture
 * manuals' register and field tables. Do not edit; change the script.
 *
 * In C, _CP0_STATUS is the register's number and _CP0_STATUS_SELECT its
 * select, and _CP0_GET_STATUS() / _CP0_SET_STATUS(v) read and write it
 * (_XCH_ exchanges, _BIS_ / _BIC_ set and clear bits, _BCS_ both, each
 * returning the old value). In assembly, _CP0_STATUS is the operand pair
 * `$12, 0`, so `mfc0 k1, _CP0_STATUS` reads it.
 */
#ifndef _CP0DEFS_H
#define _CP0DEFS_H

#if defined(__ASSEMBLER__) || defined(__LANGUAGE_ASSEMBLY__)

"""


def main():
    out = [HEAD]
    for n, r, s in REGS:
        out.append("#define _CP0_%-22s $%d, %d\n" % (n, r, s))
    out.append("\n#else /* C */\n\n#include <pic32m_builtins.h>\n\n")
    for n, r, s in REGS:
        out.append("#define _CP0_%-22s %d\n" % (n, r))
        out.append("#define _CP0_%-22s %d\n" % (n + "_SELECT", s))
    out.append("\n")
    for n, r, s in REGS:
        a = "%d, %d" % (r, s)
        out.append("#define _CP0_GET_%s() __builtin_mfc0(%s)\n" % (n, a))
        out.append("#define _CP0_SET_%s(v) __builtin_mtc0(%s, (v))\n" % (n, a))
        out.append("#define _CP0_XCH_%s(v) __builtin_mxc0(%s, (v))\n" % (n, a))
        out.append("#define _CP0_BIS_%s(set) __builtin_bsc0(%s, (set))\n"
                   % (n, a))
        out.append("#define _CP0_BIC_%s(clr) __builtin_bcc0(%s, (clr))\n"
                   % (n, a))
        out.append("#define _CP0_BCS_%s(clr, set) "
                   "__builtin_bcsc0(%s, (clr), (set))\n" % (n, a))
    out.append("\n#endif\n\n"
               "/* fields: _POSITION, _LENGTH and _MASK, in C and assembly */\n")
    for reg, f, p, l in FIELDS:
        b = "_CP0_%s_%s" % (reg, f)
        out.append("#define %s_POSITION 0x%08X\n" % (b, p))
        out.append("#define %s_LENGTH 0x%08X\n" % (b, l))
        out.append("#define %s_MASK 0x%08X\n" % (b, ((1 << l) - 1) << p))
    out.append("\n#endif\n")
    print("".join(out), end="")


if __name__ == "__main__":
    main()
