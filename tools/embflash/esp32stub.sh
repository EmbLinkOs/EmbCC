#!/bin/sh
# esp32stub.sh [OUT]: builds embflash's flasher stub (esp32stub.c, under
# esp32stub.ld) with EmbCC and writes the bytes embflash carries, to
# esp32stub.inc or OUT: each loaded piece's address and bytes, and the
# entry. The include records the SHA-256 of the source and the script it
# was built from, which tests/golden/embflash-esp.sh checks: an edit to
# either needs this run again (and a try on a board).
set -eu
here=$(dirname "$0")
root=$here/../..
EMBCC=${EMBCC:-$root/embcc}
EMBLD=${EMBLD:-$root/embld}
EMBFLASH=${EMBFLASH:-$root/embflash}
out=${1:-$here/esp32stub.inc}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
"$EMBCC" --target=xtensa-esp32-elf -Os -mtext-section-literals -Wall -Wextra -Werror \
    -c "$here/esp32stub.c" -o "$tmp/s.o"
"$EMBLD" -T "$here/esp32stub.ld" "$tmp/s.o" -o "$tmp/s.elf"
"$EMBFLASH" "$tmp/s.elf" --esp-image "$tmp/s.img" > /dev/null
python3 - "$tmp/s.img" "$here/esp32stub.c" "$here/esp32stub.ld" "$out" <<'PY'
import hashlib, struct, sys
img, src, ld, out = sys.argv[1:]
d = open(img, "rb").read()
nseg, entry = d[1], struct.unpack_from("<I", d, 4)[0]
at, segs = 24, []
for _ in range(nseg):
    addr, n = struct.unpack_from("<II", d, at)
    segs.append((addr, d[at + 8:at + 8 + n]))
    at += 8 + n
h = hashlib.sha256(open(src, "rb").read() + open(ld, "rb").read()).hexdigest()
lines = ["/* Generated by esp32stub.sh from esp32stub.c and esp32stub.ld; do not edit. */",
         f'#define ESP32STUB_SOURCE "{h}"',
         f"#define ESP32STUB_ENTRY 0x{entry:08x}u",
         f"#define ESP32STUB_NSEG {len(segs)}"]
for k, (addr, b) in enumerate(segs):
    lines.append(f"static const unsigned char g_esp32stub_{k}[{len(b)}] = {{")
    for i in range(0, len(b), 12):
        lines.append("    " + " ".join(f"0x{c:02x}," for c in b[i:i + 12]))
    lines.append("};")
lines.append("static const struct { unsigned addr, len; const unsigned char *b; } g_esp32stub[] = {")
for k, (addr, b) in enumerate(segs):
    lines.append(f"    {{ 0x{addr:08x}u, {len(b)}, g_esp32stub_{k} }},")
lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
PY
