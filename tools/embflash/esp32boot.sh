#!/bin/sh
# esp32boot.sh [OUT]: builds the ESP32 boot stub (esp32boot.c) with EmbCC and
# writes the bytes embflash carries, to esp32boot.inc or OUT. The include
# records the SHA-256 of the source it was built from, which
# tests/golden/embflash-esp.sh checks: an edit to the source needs this run
# again (and a try on a board).
set -eu
here=$(dirname "$0")
root=$here/../..
EMBCC=${EMBCC:-$root/embcc}
EMBLD=${EMBLD:-$root/embld}
EMBFLASH=${EMBFLASH:-$root/embflash}
out=${1:-$here/esp32boot.inc}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
"$EMBCC" --target=xtensa-esp32-elf -Os -mtext-section-literals -c "$here/esp32boot.c" -o "$tmp/b.o"
"$EMBLD" -e esp32boot -Ttext 0x400C0000 "$tmp/b.o" -o "$tmp/b.elf"
"$EMBFLASH" "$tmp/b.elf" --esp-image "$tmp/b.img" > /dev/null
python3 - "$tmp/b.img" "$here/esp32boot.c" "$out" <<'PY'
import hashlib, struct, sys
img, src, out = sys.argv[1:]
d = open(img, "rb").read()
nseg, entry = d[1], struct.unpack_from("<I", d, 4)[0]
addr, n = struct.unpack_from("<II", d, 24)
if nseg != 1 or addr != 0x400C0000:
    sys.exit(f"esp32boot: {nseg} segments at 0x{addr:x}; the stub is one, at 0x400C0000")
code = d[32:32 + n]
if n > 0x200:
    sys.exit(f"esp32boot: {n} bytes; the stub's table is at 0x200")
lines = ["/* Generated by esp32boot.sh from esp32boot.c; do not edit. */",
         f"#define ESP32BOOT_SOURCE \"{hashlib.sha256(open(src, 'rb').read()).hexdigest()}\"",
         f"#define ESP32BOOT_ENTRY 0x{entry - addr:x}",
         f"static const unsigned char g_esp32boot[{n}] = {{"]
for i in range(0, n, 12):
    lines.append("    " + " ".join(f"0x{c:02x}," for c in code[i:i + 12]))
lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
PY
