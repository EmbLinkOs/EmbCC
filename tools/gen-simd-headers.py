MVE_ELEMS = [('s', 8), ('s', 16), ('s', 32), ('s', 64),
             ('u', 8), ('u', 16), ('u', 32), ('u', 64), ('f', 32)]


def mve():
    o = Out()
    o(HEAD % """ * ARM's M-profile Vector Extension intrinsics (ACLE, "arm_mve.h"): the
 * 128-bit vector types, mve_pred16_t, loads and stores (and their
 * predicated forms), lane access, arithmetic and logic with their _n
 * (a scalar operand), _m (merging) and _x (don't-care) predicated forms,
 * shifts, comparisons to a predicate, vpselq, vctp, the across-vector
 * reductions and the conversions -- lane by lane over GNU vectors. A
 * predicate is a bit per byte of the vector: an element is active when
 * its lowest byte's bit is set (vctp and the comparisons set all of an
 * element's bits).""")
    o('#ifndef __EMBCC_ARM_MVE_H\n#define __EMBCC_ARM_MVE_H\n')
    o('#include <stdint.h>\n#include <string.h>\n')
    o('#ifndef __ARM_FEATURE_MVE')
    o('#error "arm_mve.h: MVE is not enabled (-march=armv8.1-m.main+mve, or -mcpu=cortex-m55)"')
    o('#endif\n')
    o('typedef uint16_t mve_pred16_t;')
    o('/* the bytes of *__s whose predicate bits are set, over *__d */')
    o('static __inline__ void __mve_merge(void *__d, const void *__s, mve_pred16_t __p)')
    o('{\n    for (int __j = 0; __j < 16; __j++)\n        if ((__p >> __j) & 1)\n'
      '            ((unsigned char *)__d)[__j] = ((const unsigned char *)__s)[__j];\n}')
    o('typedef float float32_t;\n')
    for k, b in MVE_ELEMS:
        if k == 'f':
            o('#if (__ARM_FEATURE_MVE & 2)')
        V = vtype(k, b, 128 // b)
        o('typedef %s %s __attribute__((__vector_size__(16)));' % (ctype(k, b), V))
        for m in (2, 4):
            o('typedef struct { %s val[%d]; } %sx%d_t;' % (V, m, V[:-2], m))
        if k == 'f':
            o('#endif')
    o()
    for k, b in MVE_ELEMS:
        if k == 'f':
            o('#if (__ARM_FEATURE_MVE & 2)')
        mve_type(o, k, b)
        if k == 'f':
            o('#endif')
    mve_generic(o)
    o('\n#endif')
    return o.text()


def mve_type(o, k, b):
    n = 128 // b
    eb = b // 8
    t = '%s%d' % (k, b)
    V, E = vtype(k, b, n), ctype(k, b)
    f = k == 'f'
    act = '((__p >> (__i * %d)) & 1)' % eb
    if b == 64:
        # MVE has 64-bit lanes only to move: no arithmetic, no
        # comparison, no contiguous load (its gathers take other forms)
        o.fn(E, 'vgetq_lane_%s' % t, '%s __v, const int __l' % V, '    return __v[__l];')
        o.fn(V, 'vsetq_lane_%s' % t, '%s __x, %s __v, const int __l' % (E, V),
             '    __v[__l] = __x;\n    return __v;')
        o.fn(V, 'vuninitializedq_%s' % t, 'void', '    %s __r = { 0 };\n    return __r;' % V)
        mve_reinterpret(o, k, b, t, V)
        return
    o.fn(V, 'vld1q_%s' % t, 'const %s *__b' % E,
         '    %s __r;\n    memcpy(&__r, __b, 16);\n    return __r;' % V)
    o.fn('void', 'vst1q_%s' % t, '%s *__b, %s __v' % (E, V),
         '    memcpy(__b, &__v, 16);')
    # predication is by BYTE: a lane's bytes are each its own bit's
    o.fn(V, 'vld1q_z_%s' % t, 'const %s *__b, mve_pred16_t __p' % E,
         '    %s __r = { 0 };\n    __mve_merge(&__r, __b, __p);\n    return __r;' % V)
    # ...but a store is by element: one is written when its lowest
    # byte's bit is set (what a register write merges bytewise, memory
    # takes whole)
    o.fn('void', 'vst1q_p_%s' % t, '%s *__b, %s __v, mve_pred16_t __p' % (E, V),
         loop(n, 'if (%s) __b[__i] = __v[__i];' % act))
    o.fn(V, 'vdupq_n_%s' % t, '%s __x' % E,
         '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __x;')))
    o.fn(V, 'vdupq_m_n_%s' % t, '%s __in, %s __x, mve_pred16_t __p' % (V, E),
         '    %s __t;\n%s\n    __mve_merge(&__in, &__t, __p);\n    return __in;' % (V, loop(n, '__t[__i] = __x;')))
    o.fn(E, 'vgetq_lane_%s' % t, '%s __v, const int __l' % V, '    return __v[__l];')
    o.fn(V, 'vsetq_lane_%s' % t, '%s __x, %s __v, const int __l' % (E, V),
         '    __v[__l] = __x;\n    return __v;')
    o.fn(V, 'vuninitializedq_%s' % t, 'void', '    %s __r = { 0 };\n    return __r;' % V)

    def three(name, expr, forms=('', '_m', '_x'), scalar=False):
        """name, its _m and _x forms; with scalar, the _n ones as well"""
        for fm in forms:
            for sc in ((0, 1) if scalar else (0,)):
                bt = E if sc else V
                bx = '__b' if sc else '__b[__i]'
                e = expr.replace('B', bx)
                nm = '%s%s%s_%s' % (name, fm, '_n' if sc else '', t)   # vaddq_m_n_s32
                if fm == '':
                    o.fn(V, nm, '%s __a, %s __b' % (V, bt),
                         '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = %s;' % e)))
                elif fm == '_m':
                    o.fn(V, nm, '%s __in, %s __a, %s __b, mve_pred16_t __p' % (V, V, bt),
                         '    %s __t;\n%s\n    __mve_merge(&__in, &__t, __p);\n    return __in;'
                         % (V, loop(n, '__t[__i] = (%s)(%s);' % (E, e))))
                else:
                    o.fn(V, nm, '%s __a, %s __b, mve_pred16_t __p' % (V, bt),
                         '    %s __r = { 0 };\n%s\n    return __r;' % (V, loop(n, 'if (%s) __r[__i] = %s;' % (act, e))))

    three('vaddq', '__a[__i] + B', scalar=True)
    three('vsubq', '__a[__i] - B', scalar=True)
    if b < 64:
        three('vmulq', '__a[__i] * B', scalar=True)
    if k in 'su':
        three('vandq', '__a[__i] & B')
        three('vorrq', '__a[__i] | B')
        three('veorq', '__a[__i] ^ B')
        three('vbicq', '__a[__i] & ~B')
        three('vornq', '__a[__i] | ~B')
    if b < 64 and not f:
        three('vmaxq', '(__a[__i] > B ? __a[__i] : B)')
        three('vminq', '(__a[__i] < B ? __a[__i] : B)')
        three('vabdq', '(__a[__i] > B ? __a[__i] - B : B - __a[__i])')
        wide = 'int64_t' if k == 's' else 'uint64_t'
        three('vhaddq', '(%s)(((%s)__a[__i] + B) >> 1)' % (E, wide))
        # (the saturating ones have no _x forms)
        three('vqaddq', '(%s)__sat_%s%d((%s)__a[__i] + (%s)B)' % (E, k, b, wide, wide),
              forms=('', '_m'), scalar=True)
        three('vqsubq', ('(%s)__sat_%s%d((int64_t)__a[__i] - (int64_t)B)' % (E, k, b)) if k == 's'
              else '(__a[__i] > B ? __a[__i] - B : 0)', forms=('', '_m'), scalar=True)
    if f:
        three('vmaxnmq', '(__a[__i] > B ? __a[__i] : B)')
        three('vminnmq', '(__a[__i] < B ? __a[__i] : B)')
        three('vabdq', '(__a[__i] > B ? __a[__i] - B : B - __a[__i])')
        o.fn(V, 'vfmaq_%s' % t, '%s __a, %s __b, %s __c' % (V, V, V),
             '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __a[__i] + __b[__i] * __c[__i];')))
        o.fn(V, 'vfmaq_n_%s' % t, '%s __a, %s __b, %s __c' % (V, V, E),
             '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __a[__i] + __b[__i] * __c;')))
    if b < 64 and not f:
        o.fn(V, 'vmlaq_n_%s' % t, '%s __a, %s __b, %s __c' % (V, V, E),
             '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __a[__i] + __b[__i] * __c;')))
    if k == 's' or f:
        for nm, e in (('vabsq', '__a[__i] < 0 ? -__a[__i] : __a[__i]'), ('vnegq', '-__a[__i]')):
            o.fn(V, '%s_%s' % (nm, t), '%s __a' % V,
                 '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = %s;' % e)))
    if k in 'su':
        if b < 64:
            o.fn(V, 'vmvnq_%s' % t, '%s __a' % V,
                 '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = (%s)~__a[__i];' % E)))
        o.fn(V, 'vshlq_n_%s' % t, '%s __a, const int __n' % V,
             '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = (%s)(__a[__i] << __n);' % E)))
        o.fn(V, 'vshrq_n_%s' % t, '%s __a, const int __n' % V,
             '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __n >= %d ? (%s)(%s) : (%s)(__a[__i] >> __n);'
                                                             % (b, E, '__a[__i] < 0 ? -1 : 0' if k == 's' else '0', E))))
        S = vtype('s', b, n)
        o.fn(V, 'vshlq_%s' % t, '%s __a, %s __b' % (V, S),
             '    %s __r;\n    for (int __i = 0; __i < %d; __i++) {\n'
             '        int __s = (int8_t)__b[__i];\n'
             '        __r[__i] = __s >= 0 ? (__s >= %d ? 0 : (%s)(__a[__i] << __s))\n'
             '                 : (-__s >= %d ? %s : (%s)(__a[__i] >> -__s));\n'
             '    }\n    return __r;' % (V, n, b, E, b,
                                       '(%s)(__a[__i] < 0 ? -1 : 0)' % E if k == 's' else '0', E))
    # comparisons to a predicate
    cmps = [('vcmpeqq', '=='), ('vcmpneq', '!=')]
    if k == 's' or f:
        cmps += [('vcmpgtq', '>'), ('vcmpgeq', '>='), ('vcmpltq', '<'), ('vcmpleq', '<=')]
    else:
        cmps += [('vcmphiq', '>'), ('vcmpcsq', '>=')]
    full = (1 << eb) - 1
    for nm, op in cmps:
        for sc in (0, 1):
            bt, bx = (E, '__b') if sc else (V, '__b[__i]')
            o.fn('mve_pred16_t', '%s%s_%s' % (nm, '_n' if sc else '', t), '%s __a, %s __b' % (V, bt),
                 '    mve_pred16_t __r = 0;\n%s\n    return __r;' %
                 loop(n, 'if (__a[__i] %s %s) __r |= (mve_pred16_t)(0x%x << (__i * %d));' % (op, bx, full, eb)))
    o.fn(V, 'vpselq_%s' % t, '%s __a, %s __b, mve_pred16_t __p' % (V, V),
         '    __mve_merge(&__b, &__a, __p);\n    return __b;')
    # reductions: an integer's sum in 32 bits (64 for vaddlvq), its max/min
    if not f:
        acc = 'int32_t' if k == 's' else 'uint32_t'
        if b < 64:
            o.fn(acc, 'vaddvq_%s' % t, '%s __a' % V,
                 '    %s __s = 0;\n%s\n    return __s;' % (acc, loop(n, '__s += __a[__i];')))
            o.fn(acc, 'vaddvaq_%s' % t, '%s __s, %s __a' % (acc, V),
                 '%s\n    return __s;' % loop(n, '__s += __a[__i];'))
            o.fn(acc, 'vaddvq_p_%s' % t, '%s __a, mve_pred16_t __p' % V,
                 '    %s __s = 0;\n%s\n    return __s;' % (acc, loop(n, 'if (%s) __s += __a[__i];' % act)))
            o.fn(E, 'vmaxvq_%s' % t, '%s __s, %s __a' % (E, V),
                 '%s\n    return __s;' % loop(n, '__s = __a[__i] > __s ? __a[__i] : __s;'))
            o.fn(E, 'vminvq_%s' % t, '%s __s, %s __a' % (E, V),
                 '%s\n    return __s;' % loop(n, '__s = __a[__i] < __s ? __a[__i] : __s;'))
        if b == 32:
            l = 'int64_t' if k == 's' else 'uint64_t'
            o.fn(l, 'vaddlvq_%s' % t, '%s __a' % V,
                 '    %s __s = 0;\n%s\n    return __s;' % (l, loop(n, '__s += __a[__i];')))
    if f:
        o.fn('float32_t', 'vmaxnmvq_%s' % t, 'float32_t __s, %s __a' % V,
             '%s\n    return __s;' % loop(n, '__s = __a[__i] > __s ? __a[__i] : __s;'))
        o.fn('float32_t', 'vminnmvq_%s' % t, 'float32_t __s, %s __a' % V,
             '%s\n    return __s;' % loop(n, '__s = __a[__i] < __s ? __a[__i] : __s;'))
        for ik in 'su':
            I = vtype(ik, 32, 4)
            o.fn(V, 'vcvtq_f32_%s32' % ik, '%s __a' % I,
                 '    %s __r;\n%s\n    return __r;' % (V, loop(4, '__r[__i] = (float)__a[__i];')))
            o.fn(I, 'vcvtq_%s32_f32' % ik, '%s __a' % V,
                 '    %s __r;\n%s\n    return __r;' % (I, loop(4, '__r[__i] = __cvt_%s32(__a[__i]);' % ik)))
    mve_reinterpret(o, k, b, t, V)


def mve_reinterpret(o, k, b, t, V):
    for k2, b2 in MVE_ELEMS:
        if (k2, b2) == (k, b):
            continue
        V2 = vtype(k2, b2, 128 // b2)
        g = k2 == 'f' and k != 'f'
        if g:
            o('#if (__ARM_FEATURE_MVE & 2)')
        o.fn(V, 'vreinterpretq_%s_%s%d' % (t, k2, b2), '%s __a' % V2,
             '    %s __r;\n    memcpy(&__r, &__a, 16);\n    return __r;' % V)
        if g:
            o('#endif')


def mve_generic(o):
    """the overloaded names, by _Generic on the first vector operand"""
    o('\n/* vctp: the first n elements active */')
    for b in (8, 16, 32, 64):
        eb = b // 8
        o.fn('mve_pred16_t', 'vctp%dq' % b, 'uint32_t __n',
             '    mve_pred16_t __r = 0;\n    for (uint32_t __i = 0; __i < %d && __i < __n; __i++)\n'
             '        __r |= (mve_pred16_t)(0x%x << (__i * %d));\n    return __r;' % (128 // b, (1 << eb) - 1, eb))
    names = ['vaddq', 'vsubq', 'vandq', 'vorrq', 'veorq', 'vbicq']
    for nm in names + ['vmulq', 'vmaxq', 'vminq']:
        ints = [(k, b) for k, b in MVE_ELEMS if k != 'f' and (nm not in ('vmulq', 'vmaxq', 'vminq') or b < 64)]
        flt = nm in ('vaddq', 'vsubq', 'vmulq')
        assoc = ', '.join('%s: %s_%s%d' % (vtype(k, b, 128 // b), nm, k, b) for k, b in ints)
        if flt:
            o('#if (__ARM_FEATURE_MVE & 2)')
            o('#define %s(__a, __b) _Generic((__a), %s, float32x4_t: %s_f32)(__a, __b)' % (nm, assoc, nm))
            o('#else')
        o('#define %s(__a, __b) _Generic((__a), %s)(__a, __b)' % (nm, assoc))
        if flt:
            o('#endif')
    for nm in ('vaddvq',):
        ints = [(k, b) for k, b in MVE_ELEMS if k != 'f' and b < 64]
        o('#define %s(__a) _Generic((__a), %s)(__a)' % (nm, ', '.join(
            '%s: %s_%s%d' % (vtype(k, b, 128 // b), nm, k, b) for k, b in ints)))
    ptrs = [(k, b) for k, b in MVE_ELEMS if k != 'f']
    o('#define vst1q(__p, __v) _Generic((__v), %s)(__p, __v)' % ', '.join(
        '%s: vst1q_%s%d' % (vtype(k, b, 128 // b), k, b) for k, b in ptrs))


# ---------------------------------------------------------------------------
# RISC-V V
# ---------------------------------------------------------------------------

VLEN = 128
LMULS = [('mf8', 0.125), ('mf4', 0.25), ('mf2', 0.5), ('m1', 1), ('m2', 2),
         ('m4', 4), ('m8', 8)]


def rvv_types():
    """(kind, sew, lmul-name, lmul) of every type: SEW/LMUL <= ELEN 64"""
    out = []
    for k in ('i', 'u', 'f'):
        for sew in (8, 16, 32, 64):
            if k == 'f' and sew < 32:
                continue                       # (half needs Zvfh)
            for ln, lm in LMULS:
                if sew / lm > 64:
                    continue
                out.append((k, sew, ln, lm))
    return out


def rvv_names(k, sew, ln):
    base = {'i': 'int', 'u': 'uint', 'f': 'float'}[k]
    V = 'v%s%d%s_t' % (base, sew, ln)
    E = {'i': 'int%d_t' % sew, 'u': 'uint%d_t' % sew,
         'f': 'float' if sew == 32 else 'double'}[k]
    sfx = '%s%d%s' % (k, sew, ln)
    return V, E, sfx


def rvv():
    o = Out()
    o(HEAD % """ * The RISC-V Vector extension's C intrinsics (v1.0, "riscv_vector.h"): the
 * vector types of every SEW and LMUL, the masks, vsetvl, unit-stride and
 * strided loads and stores, integer and floating-point arithmetic (and
 * their masked _m forms), logic, shifts, comparisons to a mask, merges,
 * the reductions, scalar moves, widening adds and multiplies, the
 * conversions and reinterpretations -- lane by lane over GNU vectors,
 * for a VLEN of 128 bits (the least V allows): a vector-length-agnostic
 * program, which asks vsetvl how far to go, runs as on any machine.
 * The elements past vl are left as the first operand had them (the
 * tail-agnostic policy allows anything there).""")
    o('#ifndef __EMBCC_RISCV_VECTOR_H\n#define __EMBCC_RISCV_VECTOR_H\n')
    o('#include <stddef.h>\n#include <stdint.h>\n#include <string.h>\n')
    o('#ifndef __riscv_v_intrinsic')
    o('#error "riscv_vector.h: the V extension is not enabled (-march=rv64gcv)"')
    o('#endif\n')
    for n in (1, 2, 4, 8, 16, 32, 64):
        lanes = VLEN // n
        o('typedef uint8_t vbool%d_t __attribute__((__vector_size__(%d)));' % (n, lanes))
    for k, sew, ln, lm in rvv_types():
        V, E, _ = rvv_names(k, sew, ln)
        o('typedef %s %s __attribute__((__vector_size__(%d)));' % (E, V, int(VLEN // 8 * lm)))
    o()
    for sew in (8, 16, 32, 64):
        for ln, lm in LMULS:
            if sew / lm > 64:
                continue
            vlmax = int(VLEN * lm // sew)
            o.fn('size_t', '__riscv_vsetvl_e%d%s' % (sew, ln), 'size_t __avl',
                 '    return __avl < %d ? __avl : %d;' % (vlmax, vlmax))
            o.fn('size_t', '__riscv_vsetvlmax_e%d%s' % (sew, ln), 'void',
                 '    return %d;' % vlmax)
    for k, sew, ln, lm in rvv_types():
        rvv_type(o, k, sew, ln, lm)
    for n in (1, 2, 4, 8, 16, 32, 64):
        rvv_mask(o, n)
    o('\n#endif')
    return o.text()


def rvv_mask(o, n):
    M = 'vbool%d_t' % n
    lanes = VLEN // n
    for nm, op in (('vmand', '&'), ('vmor', '|'), ('vmxor', '^'),
                   ('vmandn', '& !'), ('vmorn', '| !'), ('vmnand', 'NAND')):
        e = '!(__a[__i] & __b[__i])' if op == 'NAND' else '__a[__i] %s __b[__i]' % op
        o.fn(M, '__riscv_%s_mm_b%d' % (nm, n), '%s __a, %s __b, size_t __vl' % (M, M),
             '    %s __r = __a;\n    for (size_t __i = 0; __i < __vl && __i < %d; __i++)\n'
             '        __r[__i] = (%s) ? 1 : 0;\n    return __r;' % (M, lanes, e))
    o.fn(M, '__riscv_vmnot_m_b%d' % n, '%s __a, size_t __vl' % M,
         '    %s __r = __a;\n    for (size_t __i = 0; __i < __vl && __i < %d; __i++)\n'
         '        __r[__i] = !__a[__i];\n    return __r;' % (M, lanes))
    o.fn('unsigned long', '__riscv_vcpop_m_b%d' % n, '%s __a, size_t __vl' % M,
         '    unsigned long __c = 0;\n    for (size_t __i = 0; __i < __vl && __i < %d; __i++)\n'
         '        __c += __a[__i] != 0;\n    return __c;' % lanes)
    o.fn('long', '__riscv_vfirst_m_b%d' % n, '%s __a, size_t __vl' % M,
         '    for (size_t __i = 0; __i < __vl && __i < %d; __i++)\n'
         '        if (__a[__i])\n            return (long)__i;\n    return -1;' % lanes)
    o.fn(M, '__riscv_vmset_m_b%d' % n, 'size_t __vl',
         '    %s __r = { 0 };\n    for (size_t __i = 0; __i < __vl && __i < %d; __i++)\n'
         '        __r[__i] = 1;\n    return __r;' % (M, lanes))
    o.fn(M, '__riscv_vmclr_m_b%d' % n, 'size_t __vl',
         '    %s __r = { 0 };\n    (void)__vl;\n    return __r;' % M)


def rvv_type(o, k, sew, ln, lm):
    V, E, t = rvv_names(k, sew, ln)
    n = int(VLEN * lm // sew)
    ratio = int(sew / lm)
    M = 'vbool%d_t' % ratio
    f = k == 'f'
    lp = '    for (size_t __i = 0; __i < __vl && __i < %d; __i++)\n        ' % n

    def fn(ret, name, params, body):
        o.fn(ret, '__riscv_' + name, params, body)

    fn(V, 'vle%d_v_%s' % (sew, t), 'const %s *__b, size_t __vl' % E,
       '    %s __r = { 0 };\n%s__r[__i] = __b[__i];\n    return __r;' % (V, lp))
    fn('void', 'vse%d_v_%s' % (sew, t), '%s *__b, %s __v, size_t __vl' % (E, V),
       '%s__b[__i] = __v[__i];' % lp)
    fn(V, 'vle%d_v_%s_m' % (sew, t), '%s __m, const %s *__b, size_t __vl' % (M, E),
       '    %s __r = { 0 };\n%sif (__m[__i]) __r[__i] = __b[__i];\n    return __r;' % (V, lp))
    fn('void', 'vse%d_v_%s_m' % (sew, t), '%s __m, %s *__b, %s __v, size_t __vl' % (M, E, V),
       '%sif (__m[__i]) __b[__i] = __v[__i];' % lp)
    fn(V, 'vlse%d_v_%s' % (sew, t), 'const %s *__b, ptrdiff_t __s, size_t __vl' % E,
       '    %s __r = { 0 };\n%smemcpy(&__r[__i], (const char *)__b + (ptrdiff_t)__i * __s, sizeof __r[0]);\n    return __r;' % (V, lp))
    fn('void', 'vsse%d_v_%s' % (sew, t), '%s *__b, ptrdiff_t __s, %s __v, size_t __vl' % (E, V),
       '%s{ %s __x = __v[__i]; memcpy((char *)__b + (ptrdiff_t)__i * __s, &__x, sizeof __x); }' % (lp, E))
    # splats and scalar moves
    mv = 'vfmv' if f else 'vmv'
    xs = 'f' if f else 'x'
    fn(V, '%s_v_%s_%s' % (mv, xs, t), '%s __x, size_t __vl' % E,
       '    %s __r = { 0 };\n%s__r[__i] = __x;\n    return __r;' % (V, lp))
    fn(V, 'vmv_v_v_%s' % t, '%s __a, size_t __vl' % V,
       '    %s __r = { 0 };\n%s__r[__i] = __a[__i];\n    return __r;' % (V, lp))
    fn(E, '%s_%s_s_%s_%s' % (mv, xs, t, {'i': 'i', 'u': 'u', 'f': 'f'}[k] + str(sew)), '%s __a' % V,
       '    return __a[0];')
    fn(V, '%s_s_%s_%s' % (mv, xs, t), '%s __x, size_t __vl' % E,
       '    %s __r = { 0 };\n    if (__vl) __r[0] = __x;\n    return __r;' % V)

    def vv(name, expr, masked=False, sx=None):
        """the .vv form, and (sx) the .vx/.vf form"""
        fn(V, '%s_vv_%s' % (name, t), '%s __a, %s __b, size_t __vl' % (V, V),
           '    %s __r = __a;\n%s__r[__i] = %s;\n    return __r;' % (V, lp, expr.replace('B', '__b[__i]')))
        if sx:
            fn(V, '%s_%s_%s' % (name, sx, t), '%s __a, %s __b, size_t __vl' % (V, E),
               '    %s __r = __a;\n%s__r[__i] = %s;\n    return __r;' % (V, lp, expr.replace('B', '__b')))
        if masked:
            fn(V, '%s_vv_%s_m' % (name, t), '%s __m, %s __a, %s __b, size_t __vl' % (M, V, V),
               '    %s __r = __a;\n%sif (__m[__i]) __r[__i] = %s;\n    return __r;' % (V, lp, expr.replace('B', '__b[__i]')))

    if not f:
        vv('vadd', '__a[__i] + B', masked=True, sx='vx')
        vv('vsub', '__a[__i] - B', masked=True, sx='vx')
        fn(V, 'vrsub_vx_%s' % t, '%s __a, %s __b, size_t __vl' % (V, E),
           '    %s __r = __a;\n%s__r[__i] = __b - __a[__i];\n    return __r;' % (V, lp))
        vv('vmul', '__a[__i] * B', masked=True, sx='vx')
        sg = k == 'i'
        vv('vdiv' if sg else 'vdivu', '(B == 0 ? (%s)-1 : %s)' % (E, '(__a[__i] == %s && B == -1 ? __a[__i] : __a[__i] / B)' % ('INT%d_MIN' % sew) if sg else '__a[__i] / B'), sx='vx')
        vv('vrem' if sg else 'vremu', '(B == 0 ? __a[__i] : %s)' % ('(__a[__i] == INT%d_MIN && B == -1 ? 0 : __a[__i] %% B)' % sew if sg else '__a[__i] % B'), sx='vx')
        vv('vand', '__a[__i] & B', masked=True, sx='vx')
        vv('vor', '__a[__i] | B', masked=True, sx='vx')
        vv('vxor', '__a[__i] ^ B', masked=True, sx='vx')
        vv('vmin' if sg else 'vminu', '(__a[__i] < B ? __a[__i] : B)', sx='vx')
        vv('vmax' if sg else 'vmaxu', '(__a[__i] > B ? __a[__i] : B)', sx='vx')
        U = 'v%s%d%s_t' % ('uint', sew, ln)
        for nm, sh in (('vsll', '<<'), ('vsrl' if not sg else None, '>>'), ('vsra' if sg else None, '>>')):
            if not nm:
                continue
            fn(V, '%s_vv_%s' % (nm, t), '%s __a, %s __b, size_t __vl' % (V, U),
               '    %s __r = __a;\n%s__r[__i] = (%s)(__a[__i] %s (__b[__i] & %d));\n    return __r;' % (V, lp, E, sh, sew - 1))
            fn(V, '%s_vx_%s' % (nm, t), '%s __a, size_t __b, size_t __vl' % V,
               '    %s __r = __a;\n%s__r[__i] = (%s)(__a[__i] %s (__b & %d));\n    return __r;' % (V, lp, E, sh, sew - 1))
        fn(V, 'vnot_v_%s' % t, '%s __a, size_t __vl' % V,
           '    %s __r = __a;\n%s__r[__i] = (%s)~__a[__i];\n    return __r;' % (V, lp, E))
        if sg:
            fn(V, 'vneg_v_%s' % t, '%s __a, size_t __vl' % V,
               '    %s __r = __a;\n%s__r[__i] = (%s)(0 - __a[__i]);\n    return __r;' % (V, lp, E))
        cmps = [('vmseq', '=='), ('vmsne', '!=')] + (
            [('vmslt', '<'), ('vmsle', '<='), ('vmsgt', '>'), ('vmsge', '>=')] if sg else
            [('vmsltu', '<'), ('vmsleu', '<='), ('vmsgtu', '>'), ('vmsgeu', '>=')])
    else:
        vv('vfadd', '__a[__i] + B', masked=True, sx='vf')
        vv('vfsub', '__a[__i] - B', masked=True, sx='vf')
        vv('vfmul', '__a[__i] * B', masked=True, sx='vf')
        vv('vfdiv', '__a[__i] / B', sx='vf')
        vv('vfmin', '(__a[__i] < B ? __a[__i] : B)', sx='vf')
        vv('vfmax', '(__a[__i] > B ? __a[__i] : B)', sx='vf')
        fn(V, 'vfrsub_vf_%s' % t, '%s __a, %s __b, size_t __vl' % (V, E),
           '    %s __r = __a;\n%s__r[__i] = __b - __a[__i];\n    return __r;' % (V, lp))
        fn(V, 'vfmacc_vv_%s' % t, '%s __d, %s __a, %s __b, size_t __vl' % (V, V, V),
           '    %s __r = __d;\n%s__r[__i] = __d[__i] + __a[__i] * __b[__i];\n    return __r;' % (V, lp))
        fn(V, 'vfmacc_vf_%s' % t, '%s __d, %s __a, %s __b, size_t __vl' % (V, E, V),
           '    %s __r = __d;\n%s__r[__i] = __d[__i] + __a * __b[__i];\n    return __r;' % (V, lp))
        for nm, e in (('vfneg', '-__a[__i]'), ('vfabs', '__a[__i] < 0 ? -__a[__i] : __a[__i]'),
                      ('vfsqrt', '__builtin_sqrt%s(__a[__i])' % ('f' if sew == 32 else ''))):
            fn(V, '%s_v_%s' % (nm, t), '%s __a, size_t __vl' % V,
               '    %s __r = __a;\n%s__r[__i] = %s;\n    return __r;' % (V, lp, e))
        cmps = [('vmfeq', '=='), ('vmfne', '!='), ('vmflt', '<'), ('vmfle', '<='),
                ('vmfgt', '>'), ('vmfge', '>=')]
        I = 'vint%d%s_t' % (sew, ln)
        IE = 'int%d_t' % sew
        # toward zero, saturating -- and a NaN to the largest, as RISC-V's
        # fcvt does (ARM's gives 0)
        fn(I, 'vfcvt_rtz_x_f_v_i%d%s' % (sew, ln), '%s __a, size_t __vl' % V,
           '    %s __r = { 0 };\n%s__r[__i] = __a[__i] != __a[__i] ? INT%d_MAX : (%s)__cvt_s%d(__a[__i]);\n    return __r;'
           % (I, lp, sew, IE, 32 if sew == 32 else 64))
        fn(V, 'vfcvt_f_x_v_%s' % t, '%s __a, size_t __vl' % I,
           '    %s __r = { 0 };\n%s__r[__i] = (%s)__a[__i];\n    return __r;' % (V, lp, E))
    for nm, op in cmps:
        fn(M, '%s_vv_%s_b%d' % (nm, t, ratio), '%s __a, %s __b, size_t __vl' % (V, V),
           '    %s __r = { 0 };\n%s__r[__i] = __a[__i] %s __b[__i];\n    return __r;' % (M, lp, op))
        fn(M, '%s_v%s_%s_b%d' % (nm, 'f' if f else 'x', t, ratio), '%s __a, %s __b, size_t __vl' % (V, E),
           '    %s __r = { 0 };\n%s__r[__i] = __a[__i] %s __b;\n    return __r;' % (M, lp, op))
    fn(V, 'vmerge_vvm_%s' % t if not f else 'vmerge_vvm_%s' % t, '%s __a, %s __b, %s __m, size_t __vl' % (V, V, M),
       '    %s __r = __a;\n%s__r[__i] = __m[__i] ? __b[__i] : __a[__i];\n    return __r;' % (V, lp))
    fn(V, '%s_v%sm_%s' % ('vfmerge' if f else 'vmerge', 'f' if f else 'x', t), '%s __a, %s __b, %s __m, size_t __vl' % (V, E, M),
       '    %s __r = __a;\n%s__r[__i] = __m[__i] ? __b : __a[__i];\n    return __r;' % (V, lp))
    # reductions into an LMUL=1 vector's element 0
    V1, _, t1 = rvv_names(k, sew, 'm1')
    reds = [('vfredusum', '+'), ('vfredosum', '+'), ('vfredmax', 'max'), ('vfredmin', 'min')] if f else \
        [('vredsum', '+'), ('vredand', '&'), ('vredor', '|'), ('vredxor', '^'),
         ('vredmax' if k == 'i' else 'vredmaxu', 'max'), ('vredmin' if k == 'i' else 'vredminu', 'min')]
    for nm, op in reds:
        if op == 'max':
            st = '__s = __a[__i] > __s ? __a[__i] : __s;'
        elif op == 'min':
            st = '__s = __a[__i] < __s ? __a[__i] : __s;'
        else:
            st = '__s = __s %s __a[__i];' % op
        fn(V1, '%s_vs_%s_%s' % (nm, t, t1), '%s __a, %s __b, size_t __vl' % (V, V1),
           '    %s __s = __b[0];\n%s%s\n    %s __r = __b;\n    __r[0] = __s;\n    return __r;' % (E, lp, st, V1))
    # widening: twice the SEW at twice the LMUL
    if not f and sew < 64 and lm < 8:
        wln = [x for x, y in LMULS if y == lm * 2][0]
        W, WE, wt = rvv_names(k, sew * 2, wln)
        uu = '' if k == 'i' else 'u'
        for nm, e in (('vwadd%s' % uu, '(%s)__a[__i] + (%s)B' % (WE, WE)),
                      ('vwsub%s' % uu, '(%s)__a[__i] - (%s)B' % (WE, WE)),
                      ('vwmul%s' % uu, '(%s)__a[__i] * (%s)B' % (WE, WE))):
            fn(W, '%s_vv_%s' % (nm, wt), '%s __a, %s __b, size_t __vl' % (V, V),
               '    %s __r = { 0 };\n%s__r[__i] = %s;\n    return __r;' % (W, lp, e.replace('B', '__b[__i]')))
            fn(W, '%s_vx_%s' % (nm, wt), '%s __a, %s __b, size_t __vl' % (V, E),
               '    %s __r = { 0 };\n%s__r[__i] = %s;\n    return __r;' % (W, lp, e.replace('B', '__b')))
    # reinterpretations: the same SEW and LMUL, another kind
    for k2 in ('i', 'u', 'f'):
        if k2 == k or (k2 == 'f' and sew < 32):
            continue
        V2, _, t2 = rvv_names(k2, sew, ln)
        fn(V2, 'vreinterpret_v_%s_%s' % (t, t2), '%s __a' % V,
           '    %s __r;\n    memcpy(&__r, &__a, sizeof __r);\n    return __r;' % V2)


def write(name, text):
    path = os.path.join(INC, name)
    with open(path, 'w') as f:
        f.write(text)
    print('%s: %d lines' % (path, text.count('\n')))


def main():
    t = neon()
    t = t.replace('typedef uint8_t poly8_t;', 'typedef uint8_t poly8_t;' + NEON_HELPERS, 1)
