#!/usr/bin/env python3
"""Write include/arm_neon.h, include/arm_mve.h and include/riscv_vector.h.

    python3 tools/gen-simd-headers.py

The three intrinsic interfaces -- ACLE's Advanced SIMD (NEON), its M-profile
Vector Extension (MVE, Helium) and the RISC-V Vector extension's C
intrinsics (v1.0) -- as static inline functions over GNU vector types, each
lane by lane. EmbCC compiles a vector type as its lanes, so this is what it
would make of the instructions anyway, and it means the same program gives
the same answers on every target: tests/golden/simd-intrinsics.sh builds
its programs with these headers and with clang's, and compares.

The vector types are the ACLE's and the RVV intrinsics' own names, sized as
those ABIs size them; RVV's are given a fixed VLEN of 128 bits (the least V
allows, __riscv_v_min_vlen), so a vector-length-agnostic program -- one that
asks vsetvl and loops -- runs as it does on any machine. A function that
takes or returns one of these types passes it as EmbCC passes a structure,
not in a vector register: inside one program that is consistent, and an
object built by another compiler that passes them in v or q registers
cannot be called with one.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
INC = os.path.join(HERE, '..', 'include')

HEAD = '''/* Generated by tools/gen-simd-headers.py: do not edit by hand.
 *
%s */
'''

INLINE = 'static __inline__ __attribute__((__always_inline__, __unused__))'


def ctype(k, bits):
    return {'s': 'int%d_t' % bits, 'u': 'uint%d_t' % bits,
            'f': 'float%d_t' % bits, 'p': 'poly%d_t' % bits}[k]


def vtype(k, bits, lanes):
    base = {'s': 'int', 'u': 'uint', 'f': 'float', 'p': 'poly'}[k]
    return '%s%dx%d_t' % (base, bits, lanes)


class Out:
    def __init__(self):
        self.lines = []

    def __call__(self, s=''):
        self.lines.append(s)

    def fn(self, ret, name, params, body):
        self.lines.append('%s %s %s(%s)\n{\n%s\n}' % (INLINE, ret, name,
                                                      params, body))

    def text(self):
        return '\n'.join(self.lines) + '\n'


def loop(n, stmt):
    return '    for (int __i = 0; __i < %d; __i++)\n        %s' % (n, stmt)


# ---------------------------------------------------------------------------
# NEON
# ---------------------------------------------------------------------------

NEON_ELEMS = [('s', 8), ('s', 16), ('s', 32), ('s', 64),
              ('u', 8), ('u', 16), ('u', 32), ('u', 64),
              ('f', 32), ('f', 64), ('p', 8), ('p', 16)]


def neon():
    o = Out()
    o(HEAD % ''' * ARM's Advanced SIMD intrinsics (ACLE, "arm_neon.h"): the 64- and 128-bit
 * vector types of every element, their loads and stores, lane access,
 * arithmetic, logic, shifts, comparisons, widening and narrowing, the
 * conversions and reinterpretations, and AArch64's reductions, division
 * and square root -- written lane by lane over GNU vectors.''')
    o('#ifndef __EMBCC_ARM_NEON_H\n#define __EMBCC_ARM_NEON_H\n')
    o('#include <stdint.h>\n#include <string.h>\n')
    o('#if !defined(__ARM_NEON) && !defined(__ARM_NEON__)')
    o('#error "arm_neon.h: NEON is not enabled (AArch64, or -mfpu=neon on ARMv7-A)"')
    o('#endif\n')
    o('typedef float float32_t;\ntypedef double float64_t;')
    o('typedef uint8_t poly8_t;\ntypedef uint16_t poly16_t;\ntypedef uint64_t poly64_t;\n')
    for k, b in NEON_ELEMS:
        for total in (64, 128):
            lanes = total // b
            o('typedef %s %s __attribute__((__vector_size__(%d)));' %
              (ctype(k, b), vtype(k, b, lanes), total // 8))
            for m in (2, 3, 4):
                o('typedef struct { %s val[%d]; } %sx%d_t;' %
                  (vtype(k, b, lanes), m, vtype(k, b, lanes)[:-2], m))
    o()
    for k, b in NEON_ELEMS:
        a64only = k == 'f' and b == 64
        if a64only:
            o('#ifdef __aarch64__')
        for q in (0, 1):
            neon_type(o, k, b, q)
        neon_dq(o, k, b)
        if a64only:
            o('#endif')
    neon_reinterpret(o)
    o('\n#endif')
    return o.text()


def neon_type(o, k, b, q):
    total = 128 if q else 64
    n = total // b
    sx = 'q' if q else ''
    t = '%s%d' % (k, b)
    V, E = vtype(k, b, n), ctype(k, b)
    U = vtype('u', b, n)
    S = vtype('s', b, n)
    integer = k in 'su'
    p = k == 'p'
    f = k == 'f'
    # loads, stores, lanes
    o.fn(V, 'vld1%s_%s' % (sx, t), 'const %s *__p' % E,
         '    %s __r;\n    memcpy(&__r, __p, sizeof __r);\n    return __r;' % V)
    o.fn('void', 'vst1%s_%s' % (sx, t), '%s *__p, %s __v' % (E, V),
         '    memcpy(__p, &__v, sizeof __v);')
    o.fn(V, 'vld1%s_dup_%s' % (sx, t), 'const %s *__p' % E,
         '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = *__p;')))
    o.fn(V, 'vld1%s_lane_%s' % (sx, t), 'const %s *__p, %s __v, const int __l' % (E, V),
         '    __v[__l] = *__p;\n    return __v;')
    o.fn('void', 'vst1%s_lane_%s' % (sx, t), '%s *__p, %s __v, const int __l' % (E, V),
         '    *__p = __v[__l];')
    for nm in ('vdup%s_n_%s', 'vmov%s_n_%s'):
        o.fn(V, nm % (sx, t), '%s __x' % E,
             '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __x;')))
    D = vtype(k, b, 64 // b)
    Q = vtype(k, b, 128 // b)
    o.fn(V, 'vdup%s_lane_%s' % (sx, t), '%s __v, const int __l' % D,
         '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __v[__l];')))
    o('#ifdef __aarch64__')
    o.fn(V, 'vdup%s_laneq_%s' % (sx, t), '%s __v, const int __l' % Q,
         '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __v[__l];')))
    o('#endif')
    o.fn(E, 'vget%s_lane_%s' % (sx, t), '%s __v, const int __l' % V,
         '    return __v[__l];')
    o.fn(V, 'vset%s_lane_%s' % (sx, t), '%s __x, %s __v, const int __l' % (E, V),
         '    __v[__l] = __x;\n    return __v;')
    # structured loads and stores: vld2..4 de-interleave
    for m in (2, 3, 4):
        X = '%sx%d_t' % (V[:-2], m)
        o.fn(X, 'vld%d%s_%s' % (m, sx, t), 'const %s *__p' % E,
             '    %s __r;\n    for (int __i = 0; __i < %d; __i++)\n'
             '        for (int __j = 0; __j < %d; __j++)\n'
             '            __r.val[__j][__i] = __p[__i * %d + __j];\n    return __r;'
             % (X, n, m, m))
        o.fn('void', 'vst%d%s_%s' % (m, sx, t), '%s *__p, %s __v' % (E, X),
             '    for (int __i = 0; __i < %d; __i++)\n'
             '        for (int __j = 0; __j < %d; __j++)\n'
             '            __p[__i * %d + __j] = __v.val[__j][__i];' % (n, m, m))

    def bin_op(name, expr, ret=None):
        o.fn(ret or V, '%s%s_%s' % (name, sx, t), '%s __a, %s __b' % (V, V),
             '    %s __r;\n%s\n    return __r;' % (ret or V, loop(n, '__r[__i] = %s;' % expr)))

    def un_op(name, expr, ret=None):
        o.fn(ret or V, '%s%s_%s' % (name, sx, t), '%s __a' % V,
             '    %s __r;\n%s\n    return __r;' % (ret or V, loop(n, '__r[__i] = %s;' % expr)))

    if not p:
        bin_op('vadd', '__a[__i] + __b[__i]')
        bin_op('vsub', '__a[__i] - __b[__i]')
        if b != 64 or f:
            bin_op('vmul', '__a[__i] * __b[__i]')
            o.fn(V, 'vmla%s_%s' % (sx, t), '%s __a, %s __b, %s __c' % (V, V, V),
                 '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __a[__i] + __b[__i] * __c[__i];')))
            o.fn(V, 'vmls%s_%s' % (sx, t), '%s __a, %s __b, %s __c' % (V, V, V),
                 '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __a[__i] - __b[__i] * __c[__i];')))
            if b > 8:                   # (no vmul_n of 8-bit lanes)
                o.fn(V, 'vmul%s_n_%s' % (sx, t), '%s __a, %s __x' % (V, E),
                     '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __a[__i] * __x;')))
            bin_op('vmax', '__a[__i] > __b[__i] ? __a[__i] : __b[__i]')
            bin_op('vmin', '__a[__i] < __b[__i] ? __a[__i] : __b[__i]')
            bin_op('vabd', '__a[__i] > __b[__i] ? __a[__i] - __b[__i] : __b[__i] - __a[__i]')
        if k == 's' or f:
            un_op('vneg', '-__a[__i]')
            un_op('vabs', '__a[__i] < 0 ? -__a[__i] : __a[__i]')
        if f:
            o.fn(V, 'vfma%s_%s' % (sx, t), '%s __a, %s __b, %s __c' % (V, V, V),
                 '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __a[__i] + __b[__i] * __c[__i];')))
            o.fn(V, 'vfms%s_%s' % (sx, t), '%s __a, %s __b, %s __c' % (V, V, V),
                 '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __a[__i] - __b[__i] * __c[__i];')))
            o('#ifdef __aarch64__')
            bin_op('vdiv', '__a[__i] / __b[__i]')
            un_op('vsqrt', '__builtin_sqrt%s(__a[__i])' % ('f' if b == 32 else ''))
            o('#endif')
    if integer:
        wide = 'int64_t' if k == 's' else 'uint64_t'
        if b < 64:
            bin_op('vhadd', '(%s)(((%s)__a[__i] + __b[__i]) >> 1)' % (E, wide))
            bin_op('vrhadd', '(%s)(((%s)__a[__i] + __b[__i] + 1) >> 1)' % (E, wide))
        lo, hi = sat_bounds(k, b)
        if b < 64:
            bin_op('vqadd', '(%s)__sat_%s%d((int64_t)__a[__i] + (int64_t)__b[__i])' % (E, k, b)
                   if k == 's' else '(%s)__sat_%s%d((uint64_t)__a[__i] + __b[__i])' % (E, k, b))
            bin_op('vqsub', '(%s)__sat_%s%d((int64_t)__a[__i] - (int64_t)__b[__i])' % (E, k, b)
                   if k == 's' else '(%s)(__a[__i] > __b[__i] ? __a[__i] - __b[__i] : 0)' % E)
        else:
            bin_op('vqadd', '__qadd64_%s(__a[__i], __b[__i])' % k)
            bin_op('vqsub', '__qsub64_%s(__a[__i], __b[__i])' % k)
    if integer:                         # (none on poly lanes)
        bin_op('vand', '__a[__i] & __b[__i]')
        bin_op('vorr', '__a[__i] | __b[__i]')
        bin_op('veor', '__a[__i] ^ __b[__i]')
        bin_op('vbic', '__a[__i] & ~__b[__i]')
        bin_op('vorn', '__a[__i] | ~__b[__i]')
        if b < 64:
            un_op('vmvn', '(%s)~__a[__i]' % E)
    if integer:
        o.fn(V, 'vshl%s_n_%s' % (sx, t), '%s __a, const int __n' % V,
             '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = (%s)(__a[__i] << __n);' % E)))
        o.fn(V, 'vshr%s_n_%s' % (sx, t), '%s __a, const int __n' % V,
             '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __n >= %d ? (%s)(__a[__i] < 0 ? -1 : 0) : (%s)(__a[__i] >> __n);'
                                                              % (b, E, E) if k == 's' else
                                                              '__r[__i] = __n >= %d ? 0 : (%s)(__a[__i] >> __n);' % (b, E))))
        o.fn(V, 'vsra%s_n_%s' % (sx, t), '%s __a, %s __b, const int __n' % (V, V),
             '    return vadd%s_%s(__a, vshr%s_n_%s(__b, __n));' % (sx, t, sx, t))
        o.fn(V, 'vshl%s_%s' % (sx, t), '%s __a, %s __b' % (V, S),
             '    %s __r;\n    for (int __i = 0; __i < %d; __i++) {\n'
             '        int __s = (int8_t)__b[__i];\n'
             '        __r[__i] = __s >= 0 ? (__s >= %d ? 0 : (%s)(__a[__i] << __s))\n'
             '                 : (-__s >= %d ? %s : (%s)(__a[__i] >> -__s));\n'
             '    }\n    return __r;' % (V, n, b, E, b,
                                       '(%s)(__a[__i] < 0 ? -1 : 0)' % E if k == 's' else '0', E))
        bin_op('vtst', '(__a[__i] & __b[__i]) ? (%s)-1 : 0' % ctype('u', b), ret=U)
    if not p:
        for nm, op in (('vceq', '=='), ('vcgt', '>'), ('vcge', '>='),
                       ('vclt', '<'), ('vcle', '<=')):
            bin_op(nm, '__a[__i] %s __b[__i] ? (%s)-1 : 0' % (op, ctype('u', b)), ret=U)
    o.fn(V, 'vbsl%s_%s' % (sx, t), '%s __m, %s __a, %s __b' % (U, V, V),
         '    %s __ua, __ub, __r;\n    memcpy(&__ua, &__a, sizeof __ua);\n'
         '    memcpy(&__ub, &__b, sizeof __ub);\n%s\n'
         '    %s __o;\n    memcpy(&__o, &__r, sizeof __o);\n    return __o;'
         % (U, loop(n, '__r[__i] = (__m[__i] & __ua[__i]) | (~__m[__i] & __ub[__i]);'), V))
    o.fn(V, 'vext%s_%s' % (sx, t), '%s __a, %s __b, const int __l' % (V, V),
         '    %s __r;\n%s\n    return __r;' % (V, loop(n, '__r[__i] = __i + __l < %d ? __a[__i + __l] : __b[__i + __l - %d];' % (n, n))))
    if b == 8 and k in 'sup':
        un_op('vcnt', '(%s)__builtin_popcount((uint8_t)__a[__i])' % E)
    if integer and b < 64:
        un_op('vclz', '(%s)(__a[__i] ? __builtin_clz((uint32_t)(%s)__a[__i]) - %d : %d)'
              % (E, ctype('u', b), 32 - b, b))
    # zips: x2 results (none of 64-bit lanes: ACLE has no vzip_s64, and
    # AArch64's are vzip1q/vzip2q)
    if b == 64:
        neon_tail(o, k, b, q, n, sx, t, V, E, p, f)
        return
    X2 = '%sx2_t' % V[:-2]
    o.fn(X2, 'vzip%s_%s' % (sx, t), '%s __a, %s __b' % (V, V),
         '    %s __r;\n    for (int __i = 0; __i < %d; __i++) {\n'
         '        __r.val[__i / %d][(2 * __i) %% %d] = __a[__i];\n'
         '        __r.val[__i / %d][(2 * __i + 1) %% %d] = __b[__i];\n    }\n    return __r;'
         % (X2, n, n // 2 if n > 1 else 1, n, n // 2 if n > 1 else 1, n))
    o.fn(X2, 'vuzp%s_%s' % (sx, t), '%s __a, %s __b' % (V, V),
         '    %s __r;\n    for (int __i = 0; __i < %d; __i++) {\n'
         '        %s __x = __i < %d ? __a[2 * __i %% %d] : __b[2 * __i %% %d];\n'
         '        %s __y = __i < %d ? __a[(2 * __i + 1) %% %d] : __b[(2 * __i + 1) %% %d];\n'
         '        __r.val[0][__i] = __x;\n        __r.val[1][__i] = __y;\n    }\n    return __r;'
         % (X2, n, E, n // 2 if n > 1 else 1, n, n, E, n // 2 if n > 1 else 1, n, n))
    o.fn(X2, 'vtrn%s_%s' % (sx, t), '%s __a, %s __b' % (V, V),
         '    %s __r;\n    for (int __i = 0; __i < %d; __i += 2) {\n'
         '        __r.val[0][__i] = __a[__i];\n        __r.val[0][__i + 1] = __b[__i];\n'
         '        __r.val[1][__i] = __a[__i + 1];\n        __r.val[1][__i + 1] = __b[__i + 1];\n'
         '    }\n    return __r;' % (X2, n) if n > 1 else
         '    %s __r;\n    __r.val[0] = __a;\n    __r.val[1] = __b;\n    return __r;' % X2)
    neon_tail(o, k, b, q, n, sx, t, V, E, p, f)


def neon_tail(o, k, b, q, n, sx, t, V, E, p, f):
    def bin_op(name, expr, ret=None):
        o.fn(ret or V, '%s%s_%s' % (name, sx, t), '%s __a, %s __b' % (V, V),
             '    %s __r;\n%s\n    return __r;' % (ret or V, loop(n, '__r[__i] = %s;' % expr)))
    # AArch64 reductions
    if not p and (b < 64 or q):
        o('#ifdef __aarch64__')
        acc = E
        o.fn(acc, 'vaddv%s_%s' % (sx, t), '%s __a' % V,
             '    %s __s = 0;\n%s\n    return __s;' % (acc, loop(n, '__s += __a[__i];')))
        if b < 64 or f:
            o.fn(E, 'vmaxv%s_%s' % (sx, t), '%s __a' % V,
                 '    %s __s = __a[0];\n%s\n    return __s;' % (E, loop(n, '__s = __a[__i] > __s ? __a[__i] : __s;')))
            o.fn(E, 'vminv%s_%s' % (sx, t), '%s __a' % V,
                 '    %s __s = __a[0];\n%s\n    return __s;' % (E, loop(n, '__s = __a[__i] < __s ? __a[__i] : __s;')))
        o('#endif')
    if not q and not p and b < 64:
        bin_op('vpadd', '__i < %d ? __a[2 * __i] + __a[2 * __i + 1] : __b[2 * (__i - %d)] + __b[2 * (__i - %d) + 1]'
               % (n // 2, n // 2, n // 2))


def sat_bounds(k, b):
    if k == 's':
        return -(1 << (b - 1)), (1 << (b - 1)) - 1
    return 0, (1 << b) - 1


def neon_dq(o, k, b):
    """the D/Q pairings: combine, low/high, create, widen, narrow"""
    t = '%s%d' % (k, b)
    D, Q = vtype(k, b, 64 // b), vtype(k, b, 128 // b)
    n = 64 // b
    E = ctype(k, b)
    o.fn(Q, 'vcombine_%s' % t, '%s __lo, %s __hi' % (D, D),
         '    %s __r;\n    for (int __i = 0; __i < %d; __i++) {\n'
         '        __r[__i] = __lo[__i];\n        __r[__i + %d] = __hi[__i];\n    }\n    return __r;' % (Q, n, n))
    o.fn(D, 'vget_low_%s' % t, '%s __a' % Q,
         '    %s __r;\n%s\n    return __r;' % (D, loop(n, '__r[__i] = __a[__i];')))
    o.fn(D, 'vget_high_%s' % t, '%s __a' % Q,
         '    %s __r;\n%s\n    return __r;' % (D, loop(n, '__r[__i] = __a[__i + %d];' % n)))
    o.fn(D, 'vcreate_%s' % t, 'uint64_t __x',
         '    %s __r;\n    memcpy(&__r, &__x, 8);\n    return __r;' % D)
    if k in 'su' and b < 64:
        W = vtype(k, b * 2, 64 // b)
        WE = ctype(k, b * 2)
        o.fn(W, 'vmovl_%s' % t, '%s __a' % D,
             '    %s __r;\n%s\n    return __r;' % (W, loop(n, '__r[__i] = (%s)__a[__i];' % WE)))
        o.fn(W, 'vmull_%s' % t, '%s __a, %s __b' % (D, D),
             '    %s __r;\n%s\n    return __r;' % (W, loop(n, '__r[__i] = (%s)__a[__i] * (%s)__b[__i];' % (WE, WE))))
        o.fn(W, 'vaddl_%s' % t, '%s __a, %s __b' % (D, D),
             '    %s __r;\n%s\n    return __r;' % (W, loop(n, '__r[__i] = (%s)__a[__i] + (%s)__b[__i];' % (WE, WE))))
        o.fn(W, 'vsubl_%s' % t, '%s __a, %s __b' % (D, D),
             '    %s __r;\n%s\n    return __r;' % (W, loop(n, '__r[__i] = (%s)__a[__i] - (%s)__b[__i];' % (WE, WE))))
        o.fn(W, 'vaddw_%s' % t, '%s __a, %s __b' % (W, D),
             '    %s __r;\n%s\n    return __r;' % (W, loop(n, '__r[__i] = __a[__i] + (%s)__b[__i];' % WE)))
        o.fn(W, 'vmlal_%s' % t, '%s __a, %s __b, %s __c' % (W, D, D),
             '    %s __r;\n%s\n    return __r;' % (W, loop(n, '__r[__i] = __a[__i] + (%s)__b[__i] * (%s)__c[__i];' % (WE, WE))))
    if k in 'su' and b > 8:
        N = vtype(k, b // 2, 128 // b)
        NE = ctype(k, b // 2)
        m = 128 // b
        o.fn(N, 'vmovn_%s' % t, '%s __a' % Q,
             '    %s __r;\n%s\n    return __r;' % (N, loop(m, '__r[__i] = (%s)__a[__i];' % NE)))
        lo, hi = sat_bounds(k, b // 2)
        o.fn(N, 'vqmovn_%s' % t, '%s __a' % Q,
             '    %s __r;\n%s\n    return __r;' % (N, loop(m, '__r[__i] = (%s)(__a[__i] < %dLL ? %dLL : __a[__i] > %dLL ? %dLL : __a[__i]);'
                                                             % (NE, lo, lo, hi, hi) if k == 's' else
                                                             '__r[__i] = (%s)(__a[__i] > %dULL ? %dULL : __a[__i]);' % (NE, hi, hi))))
        if k == 's':
            U = vtype('u', b // 2, 128 // b)
            UE = ctype('u', b // 2)
            o.fn(U, 'vqmovun_%s' % t, '%s __a' % Q,
                 '    %s __r;\n%s\n    return __r;' % (U, loop(m, '__r[__i] = (%s)(__a[__i] < 0 ? 0 : __a[__i] > %dLL ? %dLL : __a[__i]);'
                                                                 % (UE, (1 << (b // 2)) - 1, (1 << (b // 2)) - 1))))
    if k == 'f' and b == 32:
        for q in (0, 1):
            sx = 'q' if q else ''
            n2 = (128 if q else 64) // 32
            F = vtype('f', 32, n2)
            for ik in 'su':
                I = vtype(ik, 32, n2)
                o.fn(F, 'vcvt%s_f32_%s32' % (sx, ik), '%s __a' % I,
                     '    %s __r;\n%s\n    return __r;' % (F, loop(n2, '__r[__i] = (float)__a[__i];')))
                # toward zero, saturating, NaN to 0 (fcvtzs/fcvtzu)
                o.fn(I, 'vcvt%s_%s32_f32' % (sx, ik), '%s __a' % F,
                     '    %s __r;\n%s\n    return __r;' % (I, loop(n2, '__r[__i] = __cvt_%s32(__a[__i]);' % ik)))
    if k == 'f' and b == 64:
        F = vtype('f', 64, 2)
        for ik in 'su':
            I = vtype(ik, 64, 2)
            o.fn(F, 'vcvtq_f64_%s64' % ik, '%s __a' % I,
                 '    %s __r;\n%s\n    return __r;' % (F, loop(2, '__r[__i] = (double)__a[__i];')))
            o.fn(I, 'vcvtq_%s64_f64' % ik, '%s __a' % F,
                 '    %s __r;\n%s\n    return __r;' % (I, loop(2, '__r[__i] = __cvt_%s64(__a[__i]);' % ik)))


def neon_reinterpret(o):
    for total in (64, 128):
        sx = 'q' if total == 128 else ''
        for k1, b1 in NEON_ELEMS:
            for k2, b2 in NEON_ELEMS:
                if (k1, b1) == (k2, b2):
                    continue
                a64 = (k1 == 'f' and b1 == 64) or (k2 == 'f' and b2 == 64)
                if a64:
                    o('#ifdef __aarch64__')
                V1, V2 = vtype(k1, b1, total // b1), vtype(k2, b2, total // b2)
                o.fn(V1, 'vreinterpret%s_%s%d_%s%d' % (sx, k1, b1, k2, b2), '%s __a' % V2,
                     '    %s __r;\n    memcpy(&__r, &__a, sizeof __r);\n    return __r;' % V1)
                if a64:
                    o('#endif')


