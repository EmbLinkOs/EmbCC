#!/usr/bin/env python3
"""evex.json -> src/arch/x86_64/evex.inc

AVX-512's EVEX forms and the opmask instructions' VEX ones, as llvm-mc
assembles them: per (mnemonic, shape) the prefix fields (map, pp, W, L'L,
b), the opcode, a ModRM reg extension, which field holds each register
operand (r ModRM reg, m ModRM rm, v vvvv, a aaa), an immediate the shape
does not show (a predicate in the mnemonic), the displacement scale
(disp8*N) and whether the form takes a mask and zeroing."""
import json, sys

OUT = sys.argv[1] if len(sys.argv) > 1 else 'evex.inc'
E = [e for e in json.load(open('evex.json')) if e['ok'] and e['mnem'][0] in 'vk']
# (a form's VEX encoding before its EVEX one: llvm-mc's choice when no
# operand needs EVEX)
E.sort(key=lambda e: (e['mnem'], e['shape'], -e['vex']))
R = {'reg': 'r', 'rm': 'm', 'vvvv': 'v', 'aaa': 'a'}
lines = ['/* AVX-512 (EVEX) and the opmask instructions (VEX), generated by',
         ' * tools/evex-isa/gen.py from what llvm-mc decodes and assembles -- facts',
         ' * measured, not a table copied. Do not edit: regenerate. */', '',
         'static const struct ev_form ev_forms[] = {']
for e in E:
    # a mask the form requires (a gather's) is a decoration to the
    # assembler, as any mask is: out of the shape, and required
    if '{K}' in e['shape']:
        e['shape'] = e['shape'].replace('{K}', '')
        e['mask'] = 3
    lines.append('    {"%s", "%s", %d, %d, %d, %d, %d, %d, 0x%02x, %d, %d, %d, %d, %d, %d, "%s"},' % (
        e['mnem'], e['shape'], e['vex'], e['map'], e['pp'], e['W'], e['LL'], e['b'], e['op'],
        e['regext'], 1 if e['imm'] else 0, e['fixed'], 1 if e['mem'] else 0, e.get('N', 1),
        e['mask'], ''.join(R[r] for r in e['roles'])))
lines.append('};')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print(len(E), 'forms ->', OUT)
