#!/usr/bin/env python3
"""Writes src/lex/xid.h: Unicode's XID_Start and XID_Continue, as ranges,
for C23's identifiers (UAX #31; C23 6.4.2.1 and Annex D).

    python3 tools/gen-xid.py > src/lex/xid.h

Python's own identifiers are XID_Start (or `_`) then XID_Continue, so
str.isidentifier is the property, from the Unicode data of the Python
that runs this; the header says which version that was. Only characters
above ASCII are listed: the lexer reads ASCII itself."""
import sys
import unicodedata


def ranges(pred):
    out = []
    lo = None
    for c in range(0x80, 0x110000):
        if 0xD800 <= c <= 0xDFFF:
            ok = False
        else:
            ok = pred(chr(c))
        if ok and lo is None:
            lo = c
        elif not ok and lo is not None:
            out.append((lo, c - 1))
            lo = None
    if lo is not None:
        out.append((lo, 0x10FFFF))
    return out


def emit(name, rs):
    print("static const unsigned int %s[][2] = {" % name)
    line = "   "
    for lo, hi in rs:
        item = " { 0x%04X, 0x%04X }," % (lo, hi)
        if len(line) + len(item) > 78:
            print(line)
            line = "   "
        line += item
    if line.strip():
        print(line)
    print("};")


start = ranges(lambda ch: ch.isidentifier())
cont = ranges(lambda ch: ("a" + ch).isidentifier())
print("/* GENERATED by tools/gen-xid.py from Unicode %s -- do not edit."
      % unicodedata.unidata_version)
print(" * XID_Start and XID_Continue above ASCII: what a C23 identifier may")
print(" * start with and go on with (UAX #31), as ranges in code point order,")
print(" * for a binary search (src/lex/lex.c, lex_ident_utf8). */")
print("#ifndef EMBCC_XID_H")
print("#define EMBCC_XID_H")
print("#define XID_UNICODE \"%s\"" % unicodedata.unidata_version)
emit("xid_start", start)
emit("xid_continue", cont)
print("#endif")
