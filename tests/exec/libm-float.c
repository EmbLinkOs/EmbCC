static float fb(uint32_t u) { float f; memcpy(&f, &u, 4); return f; }
static int32_t ord(float f)
{
    uint32_t u;
    memcpy(&u, &f, 4);
    return (u & 0x80000000u) ? -(int32_t)(u & 0x7fffffffu) : (int32_t)u;
}

static float callf(int fn, float a, float b)
{
    switch (fn) {
    case F_SIN: return sinf(a);     case F_COS: return cosf(a);
    case F_TAN: return tanf(a);     case F_ASIN: return asinf(a);
    case F_ACOS: return acosf(a);   case F_ATAN: return atanf(a);
    case F_SINH: return sinhf(a);   case F_COSH: return coshf(a);
    case F_TANH: return tanhf(a);   case F_EXP: return expf(a);
    case F_EXPM1: return expm1f(a); case F_LOG: return logf(a);
    case F_LOG10: return log10f(a); case F_LOG2: return log2f(a);
    case F_EXP2: return exp2f(a);   case F_SQRT: return sqrtf(a);
    case F_CBRT: return cbrtf(a);   case F_FLOOR: return floorf(a);
    case F_CEIL: return ceilf(a);   case F_TRUNC: return truncf(a);
    case F_ROUND: return roundf(a); case F_POW: return powf(a, b);
    case F_ATAN2: return atan2f(a, b); case F_HYPOT: return hypotf(a, b);
    case F_FMOD: return fmodf(a, b);
    }
    return 0;
}

#if __SIZEOF_DOUBLE__ == 4
static float calld(int fn, double a, double b)
{
    switch (fn) {
    case F_SIN: return sin(a);     case F_COS: return cos(a);
    case F_TAN: return tan(a);     case F_ASIN: return asin(a);
    case F_ACOS: return acos(a);   case F_ATAN: return atan(a);
    case F_SINH: return sinh(a);   case F_COSH: return cosh(a);
    case F_TANH: return tanh(a);   case F_EXP: return exp(a);
    case F_EXPM1: return expm1(a); case F_LOG: return log(a);
    case F_LOG10: return log10(a); case F_LOG2: return log2(a);
    case F_EXP2: return exp2(a);   case F_SQRT: return sqrt(a);
    case F_CBRT: return cbrt(a);   case F_FLOOR: return floor(a);
    case F_CEIL: return ceil(a);   case F_TRUNC: return trunc(a);
    case F_ROUND: return round(a); case F_POW: return pow(a, b);
    case F_ATAN2: return atan2(a, b); case F_HYPOT: return hypot(a, b);
    case F_FMOD: return fmod(a, b);
    }
    return 0;
}
#endif

static int tol(int fn)
{
    switch (fn) {
    case F_FLOOR: case F_CEIL: case F_TRUNC: case F_ROUND: case F_FMOD:
    case F_SQRT:
        return 0;
    case F_LOG2: case F_EXP2:
        return 3;
    default:
        return 2;
    }
}

static int check(const char *w, int i, float got)
{
    const struct ref *r = &refs[i];
    float want = fb(r->r);
    int32_t d = ord(got) - ord(want);
    if (d < 0) d = -d;
    if (d <= tol(r->fn) && !(want == 0 && got == 0 &&
                             (ord(want) != ord(got) ||
                              memcmp(&want, &got, 4) != 0)))
        return 0;
    printf("%s case %d (fn %d): f(%a, %a) = %a, want %a (%ld ulp)\n", w, i,
           r->fn, (double)fb(r->a), (double)fb(r->b), (double)got,
           (double)want, (long)d);
    return 1;
}

int main(void)
{
    int n = (int)(sizeof refs / sizeof refs[0]), bad = 0;
    for (int i = 0; i < n; i++) {
        bad += check("float", i, callf(refs[i].fn, fb(refs[i].a), fb(refs[i].b)));
#if __SIZEOF_DOUBLE__ == 4
        bad += check("double", i, calld(refs[i].fn, fb(refs[i].a), fb(refs[i].b)));
#endif
    }
    printf("%d cases, %d off\n", n, bad);
    return bad ? 1 : 42;
}
